function [datasets, shots] = manualShots(repo) %#ok<INUSD>
%MANUALSHOTS  What every picture in the user manual shows, and on which data.
%   [DATASETS, SHOTS] = manualShots(REPO) returns the datasets the manual's
%   pictures are made from and one entry per picture, for
%   captureManualImages.
%
%   A DATASET is a raw recording (copied into a scratch workspace) and a
%   chain of named STAGES built from it, each a transformation with its
%   options applied to a parent stage. Wherever a shipped template covers a
%   stage, the options are that template's (a struct with .template and
%   .node), so the pictures show the settings the templates use. The
%   recordings are the ones DATA.md lists: ERP CORE (Kappenman et al.,
%   2021) via Luck's textbook, the RIFT study (Dimigen et al., 2025),
%   Ehinger & Dimigen's (2019) face data, EYE-EEG's reading data and
%   FieldTrip's ERP tutorial recording.
%
%   A SHOT is one picture: a transformation's dialog, a result view, the
%   main window in some state, or a dialog the app itself opens. Its name is
%   the image file's name in manual/images.
%
%   NOT EVERY BUTTON CAN BE PHOTOGRAPHED SAFELY. ERP & Report and the other
%   exports open a system file picker first, which no timer can reach, and
%   Data Quality Report has no dialog at all: pressing it writes a report
%   into the workspace's Reports folder. The 'workspace' dataset is a real
%   one, so neither is on this list.
%
%   See also CAPTUREMANUALIMAGES.
    tpl = @(file, node) struct('template', file, 'node', node);
    % A template node with some of its options replaced (captureManualImages'
    % resolveParams applies OVERRIDE over the template's own).
    tplWith = @(file, node, override) struct('template', file, 'node', node, 'override', override);
    ch02 = 'library/templates/luck/ch02-N400-one-participant.alztemplate';
    ch08 = 'library/templates/luck/ch08-N2pc.alztemplate';
    ch09 = 'library/templates/luck/ch09-MMN-with-ICA.alztemplate';
    ch10 = 'library/templates/luck/ch10-LRP.alztemplate';
    rift = 'library/templates/dimigen-rift-simplified.alztemplate';
    face = 'library/templates/FaceSaccadesDeconvolution.alztemplate';
    reading = 'library/templates/ReadingDeconvolution.alztemplate';
    fterp = 'library/templates/fieldtrip/preprocessing-erp.alztemplate';
    init = struct('Param', 'Init');

    % ---- options the templates do not carry -------------------------------
    tfOpts = struct('MinFreq', 3, 'MaxFreq', 30, 'NumFreqs', 28, 'MinCycles', 3, ...
        'MaxCycles', 8, 'BaselineStart', -200, 'BaselineStop', 0);
    fourierOpts = struct('Output', 'PSD', 'FullSpectrum', false, 'Window', 'Hanning', ...
        'Window_Length', 10, 'Resolution', 'Max', 'ResVal', 1);
    welchOpts = struct('SegmentSeconds', 2, 'Overlap', 50, 'Window', 'Hanning');
    covOpts = struct('Channels', {{}}, 'Statistic', 'Correlation', 'Shrinkage', 'Ledoit-Wolf', ...
        'Start', 300, 'Stop', 500);
    xcorrOpts = struct('RefChannel', 'VEOG', 'Channels', {{}}, 'MaxLagMs', 100, ...
        'MinPairs', 20, 'Start', 0, 'Stop', 0);
    % Three detectors, for a Rejection breakdown with something to show: the
    % manual's Table/Figure on it quotes these numbers (93 of 231 epochs).
    threeDetectors = struct('Method', {{'Absolute threshold', 'Step function', ...
        'Moving-window peak-to-peak'}}, 'Minimum', -100, 'Maximum', 100, ...
