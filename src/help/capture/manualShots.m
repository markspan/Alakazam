function ds = dataset(key, files, stages)
    ds = struct('key', key, 'kind', 'recording', 'workspace', '', 'files', {cellstr(files)}, ...
        'stages', [stages{:}], 'template', '');
    if isempty(stages)
        ds.stages = struct('name', {}, 'parent', {}, 'transform', {}, 'params', {});
    end
end

function s = stg(name, parent, transform, params)
    s = struct('name', name, 'parent', parent, 'transform', transform, 'params', params);
end

function s = shot(name, dataset, kind, varargin)
%SHOT  One picture. Kinds: 'dialog' (a transformation's own dialog on the
%   stage INPUT, its fields seeded with SEED), 'view' (the stage INPUT's
%   result view), 'window' (the main window, after selecting SELECT in TREE
%   and showing RIBBONTAB), 'appdialog' (the dialog behind a ribbon button,
%   ACTION), 'method' (the window an app method opens, ACTION) and 'call'
%   (a dialog opened on the stage INPUT by ACTION, a function of EEG and
%   the app). There is no kind for a uialert, which exportapp cannot
%   capture. A view is
%   put in its state by CHANNEL, BIN, SORT (an ERP image's sort key), ONLY
%   (the series an ERP plot shows), TIME (a scalp map's instant),
%   PROJECTION (Brain3D's), OVERLAY (a stage drawn in the same plot) and
%   XLIM (a spectrum's frequency range).
%   CROP is 'plot', 'ribbon' or 'window'; SETTLE the seconds a dialog is
%   given to draw; DIALOGTAB the tab a tabbed dialog is shown on.
    s = struct('name', name, 'dataset', dataset, 'kind', kind, 'input', '', ...
        'transform', '', 'seed', [], 'settle', 4, 'dialogTab', '', 'channel', '', ...
        'bin', '', 'sort', '', 'only', {{}}, 'time', [], 'projection', '', 'overlay', '', ...
        'select', '', 'tree', 'Tree', 'ribbonTab', '', 'crop', 'plot', 'action', '', ...
        'xlim', []);
    for k = 1:2:numel(varargin)
        s.(varargin{k}) = varargin{k + 1};
    end
end
