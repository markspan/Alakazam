        'FitStart', -200, 'FitStop', 0);
    rectifyOpts = struct('Channels', {{}}, 'Mode', 'Full wave (|x|)');
    % The automated cleaning steps with their defaults, except PREP's line
    % frequency: ERP CORE was recorded in California, on 60 Hz mains.
    prepOpts = struct('LineFrequency', '60', 'DeviationThreshold', 5, ...
