        'refChannel', 'Photodiode', 'method', 'Hann', 'tapers', 3, 'snrNeighbours', 10, ...
        'snrGuard', 1, 'coherenceMethod', 'frames', ...
        'crossf', struct('enabled', false, 'Method', 'frames', 'WinSize', 510, ...
