        stg('waveforms', 'raw', 'Deconvolve', tpl(face, 1)), ...
        stg('trials', 'raw', 'Deconvolve', tpl(face, 2)), ...
        stg('epochs', 'raw', 'DefineBins', tpl(face, 3)), ...
