        'trials', struct('mode', '(off)', 'indices', []));
    sourceOpts = struct('Method', 'mne', 'Orientation', 'normal', 'SourceSpace', 5124, ...
        'TimeWindow', [-200 795], 'ResampleHz', 200, 'RegParam', 0.05, ...
        'NoiseCovariance', 'baseline', 'SNR', 3, ...
        'WindowStart', -200, 'WindowStop', 795);
    regionOpts = struct('Atlas', 'AAL', 'Value', 'Signed mean', 'Method', 'dSPM', ...
        'SourceSpace', '5124', 'NoiseCovariance', 'auto', 'SNR', 3, 'RegParam', 0.05);
    % The dialog shows the default optimiser, FieldTrip's choice; the fit
    % behind the result picture uses fminsearch, which runs on every MATLAB,
