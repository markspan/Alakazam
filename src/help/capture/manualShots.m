    % Designer. The designed filter is the struct designedFilterFromObject
    % makes, written out here because this list is read before the app has
    % put the Filter folder on the path.
    lineNoiseStop = designfilt('bandstopiir', 'FilterOrder', 4, 'HalfPowerFrequency1', 48, ...
        'HalfPowerFrequency2', 52, 'SampleRate', 200);
    filterOpts = struct('perChannel', false, ...
        'highpass', struct('enabled', true, 'freq', 0.1, 'db', 40, 'auto', true, 'transition', [], 'order', []), ...
