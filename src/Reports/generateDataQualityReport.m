function lines = dependabilityLines(measureCsvName)
%DEPENDABILITYLINES  Dependability from generalizability theory, and the
%   trial count a target dependability would need.
%
%   THE QUESTION THE REST OF THIS REPORT ONLY GESTURES AT. Rejection rates
%   say how much was lost. SME says what the loss cost, in the units of the
%   measure. Neither says whether the measure is reliable enough to
%   correlate with anything, which is the question behind every "how many
%   trials do I need" a reader has ever asked, and it is the question
%   generalizability theory answers (Clayson & Miller, 2017).
%
%   G THEORY IN ONE PARAGRAPH. Score a component on single trials and the
%   variance splits in two: variance BETWEEN people, which is the signal a
%   correlation or a group difference can use, and variance WITHIN a person
%   across trials, which is noise that averaging reduces. Dependability is
%   the first as a fraction of what an average of n trials actually
%   measures, sigma_p^2 / (sigma_p^2 + sigma_e^2 / n). It rises with trial
%   count without bound in principle, which is why the useful output is not
%   the coefficient alone but the n that reaches a target.
%
%   FITTED WITH lmer, NOT BY ANOVA MEAN SQUARES. Trial counts differ per
%   person after rejection, sometimes by a factor of three, and the ANOVA
%   estimator assumes they do not. A random-intercept model handles the
%   imbalance properly and is the one place in this report that needs a
%   package beyond tidyverse.
%
%   ONLY WHERE Measure RAN ON EPOCHED DATA. Averaged measurements carry one
%   value per person and condition, from which no within-person variance is
%   recoverable at all. The section says so rather than approximating, since
%   precisionByTrialCountLines already gives the honest approximation.
    if isempty(measureCsvName)
        lines = { ...
            '## Dependability' ...
            '' ...
            ['Not computed for this report. Dependability needs the scored value of ' ...
             '**each trial**, and no dataset in this workspace carried per-trial ' ...
             'measurements. To get them, run `Measure` on the **epoched** node rather ' ...
             'than on the Average: the same window definitions then yield one value ' ...
             'per trial instead of one per bin, and this section computes itself the ' ...
             'next time the report is generated. In the absence of those values, ' ...
             '*Precision Against Trial Count* above gives an approximation, and is ' ...
             'labelled as such.'] ...
            '' ''};
        return;
    end
    lines = ReportDoc.lines({ ...
        '## Dependability' ...
        '' ...
        ['The reliability of each measure, and the number of trials a target ' ...
         'reliability would require. Single-trial amplitude varies both between ' ...
         'people, which is the variance any correlation or group difference uses, ' ...
         'and within a person from trial to trial, which is noise that averaging ' ...
         'reduces. Dependability is the first of these as a fraction of what an ' ...
         'average of *n* trials measures, and is the quantity generalizability ' ...
         'theory estimates (Clayson & Miller, 2017).'] ...
        ReportDoc.template('dq-dependability.qmd') ...
        ['The last two columns are design quantities rather than criteria. They ' ...
         'assume that additional trials would resemble the existing ones, an ' ...
         'assumption that fatigue and drift weaken towards the end of a long ' ...
         'session, so the counts are a lower bound on the required effort. A ' ...
         'score whose dependability is below about .70 constrains any correlation ' ...
         'it can enter, irrespective of sample size.'] ...
        '' ''});
end

