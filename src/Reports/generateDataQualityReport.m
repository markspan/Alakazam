% ======================================================================= %
%  Closing: what to look at
% ======================================================================= %
function lines = precisionByTrialCountLines()
%PRECISIONBYTRIALCOUNTLINES  Measurement precision against surviving trial
%   count, with the theoretical curve drawn through it.
%
%   THE QUESTION EVERY REJECTION DECISION IS REALLY ASKING. The rest of this
%   report says how many trials each subject lost. It does not say what that
%   loss cost, and those are different questions: losing 40 trials from 200
%   barely moves the estimate, losing 20 from 40 changes what the average
%   means. The standardised measurement error answers it directly, because
%   it is the standard error of the very quantity being measured (Luck et
%   al., 2021), and plotting it against surviving trial count turns a
%   diagnostic into a design number.
%
%   The reference curve is 1/sqrt(n). Averaging independent trials reduces
%   the standard error by that factor and no faster, so a subject sitting
%   well above the curve is not short of trials but noisy within them, which
%   collecting more of would not fix. That distinction is the practical
%   value of the figure: it separates "run more trials" from "this
%   recording has a problem".
%
%   NOT A DEPENDABILITY COEFFICIENT, and no longer the only answer here.
%   Generalizability theory (Clayson & Miller, 2017) estimates how many
%   trials a given component needs for a target reliability, which is the
%   fuller answer to the same question and needs per-trial VALUES of the
%   measure rather than per-trial noise. dependabilityLines below computes
%   exactly that when the per-trial measurement export is present. This
%   figure stays because it needs nothing beyond SME and so is always
%   available, and because it separates two failures the coefficient pools:
%   a subject short of trials sits on the curve, one noisy within them sits
%   above it.
    lines = ReportDoc.lines({ ...
        '## Precision Against Trial Count' ...
        '' ...
        ['The measurement precision obtained from the trials that survived, per subject. The ' ...
         'standardised measurement error is the standard error of the measure itself, so it ' ...
         'addresses what a rejection rate does not: not how much data was lost, but the effect ' ...
         'of that loss on the estimate.'] ...
        ReportDoc.template('dq-precision-by-trials.qmd') ...
        ['This is an approximation to the question generalizability theory answers properly ' ...
         '(Clayson & Miller, 2017): how many trials a given component needs to reach a target ' ...
         'reliability. That calculation uses the per-trial values of the measure itself rather ' ...
         'than per-trial noise, which this report does not yet read.'] ...
        '' ''});
end

function lines = attentionLines()
    lines = ReportDoc.lines({ ...
        '## Worth a Look' ...
        '' ...
        ['A shortlist for inspection, not a set of exclusion decisions. Nothing here has been ' ...
         'excluded, and none of these thresholds is a standard: they are conventional starting ' ...
         'points, set at values that merit a second look rather than at values that are ' ...
         'correct. Whether a subject at 35% rejection is usable depends on the initial trial ' ...
         'count and on what is being measured.'] ...
        ReportDoc.template('dq-attention-list.qmd') ...
        ['| More than **25%** of trials discarded | At a quarter of the data gone, the surviving ' ...
         'trials are no longer a random subset: whatever removed them (drowsiness, movement, ' ...
         'drift) is systematic, and is likely to correlate with condition or with time in the ' ...
         'session. Below roughly this level, loss behaves more like attrition than like bias |'] ...
        ['| Fewer than **20** surviving trials in a bin that began with more than 20 | Noise in an ' ...
         'average falls as 1/sqrt(*n*), so returns diminish quickly, but below about 20 trials the ' ...
         'average is still visibly unstable for a typical ERP component and the SME grows sharply. ' ...
         'Luck et al. (2021) argue the SME column is the better guide here, since it accounts for ' ...
         'how noisy the individual trials actually were; this count is the cruder proxy that needs ' ...
         'no measurement window to have been defined yet. The second half of the condition matters: ' ...
         'a bin designed with 15 trials has not lost anything, and flagging it would report the ' ...
         'design rather than the data |'] ...
        ['| A channel flagged in more than **20%** of trials | A channel that fails this often is ' ...
         'usually a bad electrode rather than an occasional artefact, and one persistently bad ' ...
         'channel is a case for interpolation rather than for discarding trials |'] ...
        ['| A channel interpolated in more than **20%** of trials | The same threshold applied to ' ...
         'repair rather than loss. Interpolated samples pass every other check in this report as ' ...
         'ordinary data, so this is the only place a mostly-reconstructed channel appears |'] ...
        ['| A subject more than **3 MAD** noisier than the sample median | Median absolute ' ...
         'deviation rather than standard deviation, because with a handful of subjects the very ' ...
         'outliers being looked for would inflate an SD enough to hide inside it. 3 MAD is the ' ...
         'usual robust-statistics analogue of a 3-sigma rule |'] ...
        ['| Any trial truncated at a recording boundary | Not a threshold: any occurrence is ' ...
         'reported, because such a trial still enters the average with less data at the ends ' ...
         'than its neighbours, and no other section of the report would reveal it |'] ...
        '' ...
        ['These are applied per subject, and the report flags rather than acts. Exclusion criteria ' ...
