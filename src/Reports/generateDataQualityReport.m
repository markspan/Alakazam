function lines = provenanceLines(provenanceCsvName)
%PROVENANCELINES  What each cleaning step actually did: which detector cost
%   which trials, and what the correction steps removed.
%
%   The sections above say how much data was lost. This one says what lost
%   it, which is the part that tells you what to change. Rejection and
%   correction are recorded on the dataset as they run, so this is a report
%   of what happened rather than a re-derivation of it.
%
%   A NOTE ON ONE ESCAPE BELOW, because getting it wrong cost a whole
%   report: a literal double quote inside an emitted R string is \" and NOT
%   \\". This is MATLAB source writing R source, and a MATLAB single-quoted
%   literal passes backslashes through untouched, so \\" arrives in the .qmd
%   as \\" -- which R reads as a literal backslash followed by a quote that
%   CLOSES the string. The chunk becomes a syntax error and Quarto renders
%   nothing at all. Compare the callout-tip line in attentionLines, which
%   does it right. (The opposite convention applies to a backslash meant for
%   the OUTPUT, such as LaTeX's \chi: there \\ is correct, because R's parser
%   consumes one level before cat ever runs. See rejectionByBinLines.)
%
%   Two more things this function's own shape demands. The emitted prose
%   below carries NO APOSTROPHES: one inside a MATLAB single-quoted literal
%   has to be doubled, and rephrasing to avoid it is cheaper than an escape
%   that a later edit can break. And NO COMMENT LINE may sit inside the
%   lines = {...} literal: every line there ends with a continuation, so a
%   comment ends the row and the cell becomes a vertcat of rows of unequal
%   width. Comments about the emitted R belong in the R, as # lines.
    if isempty(provenanceCsvName)
        lines = {};
        return;
    end
    lines = ReportDoc.lines({ ...
        '## What the Cleaning Steps Did' ...
        '' ...
        ['How much data was lost is above; this is what lost it. Each cleaning step ' ...
         'records what it did as it runs, so these are the decisions themselves rather ' ...
         'than an estimate of them.'] ...
        '' ...
        ['A table per step, and only for the steps that ran. They are kept separate ' ...
         'because they count different things: epochs for rejection, components for ' ...
         'ICA, channels and samples for GEDAI. One combined table could only have ' ...
         'labelled its count column "n", which no reader could interpret.'] ...
        ReportDoc.template('dq-provenance.qmd') ...
        });
end

