function qmdText = generateDataQualityReport(entries, summaryCsvName, trialCsvName, smeCsvName, measureCsvName, provenanceCsvName)
%GENERATEDATAQUALITYREPORT  A Quarto (.qmd) report on per-subject ERP data
%   quality: rendering it (self-contained HTML) produces a per-subject
%   overview table, the condition-wise rejection figure that is the whole
%   point of the exercise, per-trial noise distributions, a subject x
%   channel noise map, and a short "worth a look" list naming the subjects
%   and channels that stand out.
%
%   Adapted from the data-quality assessment section of Mathot &
%   Vilotijevic (2023), "Methods in cognitive pupillometry: Design,
%   preprocessing, and statistical analysis" (Behav Res Methods 55,
%   3055-3077) -- see dataQualityMetrics.m's own header for the
%   pupillometry-to-ERP mapping each metric comes from, and for the two
%   places the translation deliberately departs from the original.
%
%   Like generateClusterStatsReport.m (and unlike generateQuartoReport.m,
%   whose R code runs the actual statistical tests), every number here was
%   already computed in MATLAB by dataQualityMetrics; this report's own R
%   code narrates, tabulates and plots a precomputed result. The one
%   exception is the omnibus test for whether rejection rate differs
%   BETWEEN bins, which is a genuine inferential question about the export
%   as a whole rather than about any one subject, so it belongs with the
%   other cross-subject statistics in R.
%
%   ENTRIES is the same struct array exportDataQualityCSVs was handed (only
%   its length and grouping are used here, to decide which sections can
%   run at all); SUMMARYCSVNAME/TRIALCSVNAME are bare filenames, resolved
%   relative to the .qmd's own folder.
%
%   Requires the R packages tidyverse and gt (auto-installed by the
%   report's own setup chunk on first render, same as the other two report
%   generators) plus a working Quarto installation.
%
%   See also DATAQUALITYMETRICS, EXPORTDATAQUALITYCSVS,
%   ALAKAZAM.ONEXPORTDATAQUALITY.
    if isempty(entries)
        throw(MException('Alakazam:generateDataQualityReport', ...
            ['I''m afraid a data-quality report needs at least one Averaged dataset ' ...
             'with segmented data behind it.']));
    end
    hasGroups = numel(distinctGroups(entries)) >= 2;
    if nargin < 4 || isempty(smeCsvName)
        smeCsvName = '';
    end
    if nargin < 5 || isempty(measureCsvName)
        measureCsvName = '';
    end
    if nargin < 6 || isempty(provenanceCsvName)
        provenanceCsvName = '';
    end

    lines = [ ...
        preambleLines(summaryCsvName, trialCsvName, smeCsvName, measureCsvName, ...
            provenanceCsvName), ...
        introLines(numel(entries)), ...
        overviewLines(), ...
        rejectionByBinLines(), ...
        baselineNoiseLines(), ...
        noiseOverSessionLines(), ...
        channelNoiseLines(), ...
        flaggedByChannelLines(), ...
        provenanceLines(provenanceCsvName), ...
        smeLines(smeCsvName), ...
        precisionByTrialCountLines(), ...
        dependabilityLines(measureCsvName), ...
        groupComparisonLines(hasGroups), ...
        attentionLines()];
    qmdText = strjoin(lines, newline);
end

% ======================================================================= %
function lines = flaggedByChannelLines()
%FLAGGEDBYCHANNELLINES  How many trials each channel was flagged in, per
%   subject, as a count rather than a proportion.
%
%   THE MAP ABOVE ANSWERS A DIFFERENT QUESTION. Noise by Channel is
%   coloured by median pre-stimulus SD and marks a channel flagged in more
%   than 20% of trials with a cross. That is a threshold, not a number: it
%   separates 21% from 19% and says nothing about whether a flagged
%   channel lost 12 trials or 200, which is the quantity that decides
%   whether to interpolate it, drop it, or leave it.
%
%   Counts, not percentages, and printed in the cell. A percentage hides
%   the trial count it is a percentage of, and two subjects at 30% are not
%   comparable when one ran 40 trials and the other 400. The percentage is
%   kept as the fill, so the eye still finds the worst cells first while
%   the number gives the amount.
%
%   Peripherals are marked rather than hidden. An EOG channel exceeds any
%   threshold set for scalp EEG on every blink, so it is flagged on a large
%   fraction of trials whenever artefact detection tests it, and appearing
%   here at 60% is correct rather than a fault. Hiding it would conceal
%   that the detector is spending its threshold on the eyes; labelling it
%   lets a reader skip it and read the scalp channels, which are the ones a
%   decision hangs on. See ArtefactDetect's own "Channels to test" option.
    lines = ReportDoc.lines({ ...
        '### Trials flagged, per channel and subject' ...
        '' ...
        ['The number of trials in which each channel was flagged, for each subject. ' ...
         'Colour is that count as a proportion of the subject''s own trials, so the ' ...
         'worst cells stand out, and the number in the cell is the count itself, ' ...
         'which is what a decision to interpolate or exclude a channel actually ' ...
         'rests on.'] ...
        ReportDoc.template('dq-flagged-by-channel.qmd') ...
        '' ''});
end

