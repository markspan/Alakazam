function line = smeReadLine(smeCsvName)
%SMEREADLINE  Read the per-window SME table, or stand in an empty one of
%   the same shape when this export had no Measure results to score. The
%   section below then needs only ONE emptiness check (nrow == 0), rather
%   than separate "file absent" and "file empty" branches that would both
%   have to be kept in step with it.
    if isempty(smeCsvName)
        line = ['wsme <- tibble(dataset = character(), group = character(), window = character(), ' ...
            'bin = character(), channel = character(), measure = character(), method = character(), ' ...
            'sme_uv = double(), score = double())'];
    else
        line = sprintf('wsme <- read_csv("%s", show_col_types = FALSE)', rLit(smeCsvName));
    end
end

