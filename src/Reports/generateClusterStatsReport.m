% ======================================================================= %
%  Per-cluster detail (strongest few, already p-sorted -- see this file's
%  own header on why not every spurious tiny cluster gets a full section)
% ======================================================================= %
function lines = clusterDetailLines(summary)
%CLUSTERDETAILLINES  The strongest clusters, one section each.
%
%   THE HEADING USED TO SAY "Where and When", which is the one reading this
%   analysis cannot support, directly above a sentence listing channels and a
%   time range. The report's own caveat said so, but it was emitted further
%   down beside the null distribution, so a reader met the claim first and the
%   correction later. The caveat now opens this section instead: the sentence
%   that invites the error and the sentence that forbids it belong together.
    lines = {'## The Strongest Clusters' '' ...
        ['A cluster''s extent is a by-product of the cluster-forming threshold and the ' ...
         'noise, not an estimate of anything. The channels and times below say where the ' ...
         'statistic ran extreme in this dataset; they do not say where or when the effect ' ...
         'begins and ends, and the *p*-value belongs to the test as a whole rather than to ' ...
         'those boundaries (Sassenhagen & Draschkow, 2019).'] ''};
    nShow = min(5, numel(summary.clusters));
    if nShow == 0
        lines = [lines, {'No clusters to show.' ''}];
        return;
    end
    space = testedSpace(summary);
    for r = 1:nShow
        c = summary.clusters(r);
        lines = [lines, oneClusterLines(r, c, space)]; %#ok<AGROW>
    end
end

function space = testedSpace(summary)
%TESTEDSPACE  How large the tested channel x time space was, read from
%   FieldTrip's own stat (summary.stat.label / .time). NaN where it cannot be
%   read, which is how a summary from before this existed still reports.
    space = struct('nChannels', NaN, 'spanMs', NaN);
    if ~isfield(summary, 'stat') || ~isstruct(summary.stat)
        return;
    end
    if isfield(summary.stat, 'label')
        space.nChannels = numel(summary.stat.label);
    end
    if isfield(summary.stat, 'time') && numel(summary.stat.time) > 1
        space.spanMs = (max(summary.stat.time) - min(summary.stat.time)) * 1000;
    end
end

function lines = coverageLines(c, space)
%COVERAGELINES  How much of the tested space this cluster covers, in the
%   report rather than left to the reader to work out from a list of channel
%   names. A cluster covering nearly everything is the common case people
%   over-read: it is what a broad sustained difference produces, and its
%   boundaries then carry almost no information at all.
    lines = {};
    if ~isfinite(space.nChannels) || ~isfinite(space.spanMs) || space.spanMs <= 0
        return;
    end
    spanMs = c.timeRangeMs(2) - c.timeRangeMs(1);
    text = sprintf('It covers %d of the %d channel(s) tested, and %.0f of the %.0f ms.', ...
        numel(c.channels), space.nChannels, spanMs, space.spanMs);
    if numel(c.channels) / space.nChannels >= 2/3 && spanMs / space.spanMs >= 0.5
        text = [text ' That is most of the space the test looked at, so its extent says ' ...
            'very little: a cluster this broad is what a sustained, widespread difference ' ...
            'produces, and it cannot be told apart from one confined to part of that space.'];
    end
    lines = {'' text};
end

function lines = oneClusterLines(rank, c, space)
    sigWord = 'not significant';
    if c.significant
        sigWord = 'significant';
    end
    chLit = rLit(strjoin(c.channels, ', '));
    heading = { ...
        sprintf('### Cluster %d (%s, %s)', rank, c.sign, sigWord) ...
        '' ...
        sprintf(['A %s cluster spanning %s, %.0f to %.0f ms (*p* %s, %d point(s)).'], ...
            c.sign, mdLit(strjoin(c.channels, ', ')), c.timeRangeMs(1), c.timeRangeMs(2), ...
            pStr(c.pValue), c.nPoints)};
    lines = [heading, coverageLines(c, space), { ...
        '' ...
        '::: {layout-ncol=2}' ...
        '' ...
        sprintf('```{r}') ...
        sprintf('#| label: topo-%d', rank) ...
        sprintf('#| fig-width: 4') ...
        sprintf('#| fig-height: 4') ...
        sprintf('t_lo <- %g; t_hi <- %g', c.timeRangeMs(1), c.timeRangeMs(2)) ...
        sprintf('pts <- stat_df %%>%% filter(time_ms >= t_lo, time_ms <= t_hi) %%>%%') ...
        sprintf('  group_by(channel, x, y) %%>%% summarise(statistic = mean(statistic), .groups = "drop")') ...
        sprintf('in_cluster <- stat_df %%>%% filter(channel %%in%% c(%s), time_ms >= t_lo, time_ms <= t_hi) %%>%%', ...
            strjoin(cellfun(@(ch) ['"' rLit(ch) '"'], c.channels, 'UniformOutput', false), ', ')) ...
        sprintf('  distinct(channel)') ...
        sprintf('tp <- ggplot() +') ...
        sprintf('  geom_path(data = outline_df, aes(x = x, y = y, group = outline_id), colour = "grey60") +') ...
        sprintf('  geom_point(data = pts, aes(x = x, y = y, colour = statistic), size = 5) +') ...
        sprintf(['  geom_point(data = pts %%>%% filter(channel %%in%% in_cluster$channel), ' ...
            'aes(x = x, y = y), shape = 1, size = 7, colour = "black", stroke = 1) +']) ...
        sprintf(['  geom_text(data = pts, aes(x = x, y = y, label = channel), ' ...
            'size = 2.2, vjust = -1.1, colour = "grey20") +']) ...
        sprintf('  scale_colour_gradient2(low = "#c0392b", mid = "white", high = "#2980b9", midpoint = 0) +') ...
        sprintf('  coord_fixed() + theme_void() + labs(title = "Where (mean over cluster window)")') ...
        sprintf('print(tp)') ...
        '```' ...
        '' ...
        sprintf('```{r}') ...
        sprintf('#| label: timecourse-%d', rank) ...
        sprintf('#| fig-width: 5') ...
        sprintf('#| fig-height: 4') ...
        sprintf('wf <- waveform_df %%>%% filter(channel %%in%% c(%s))', ...
            strjoin(cellfun(@(ch) ['"' rLit(ch) '"'], c.channels, 'UniformOutput', false), ', ')) ...
        sprintf('tc <- ggplot(wf, aes(x = time_ms, y = value, colour = condition, fill = condition)) +') ...
        sprintf('  annotate("rect", xmin = t_lo, xmax = t_hi, ymin = -Inf, ymax = Inf, alpha = 0.12, fill = "grey40") +') ...
        sprintf('  stat_summary(fun = mean, geom = "line", linewidth = 0.8) +') ...
        sprintf('  stat_summary(fun.data = mean_se, geom = "ribbon", alpha = 0.15, colour = NA) +') ...
        sprintf('  geom_hline(yintercept = 0, linetype = "dashed", colour = "grey60") +') ...
        sprintf('  labs(x = "Time (ms)", y = "Amplitude", title = "When (shaded = cluster window)") +') ...
        sprintf('  alz_theme()') ...
        sprintf('print(tc)') ...
        '```' ...
        '' ...
        ':::' ...
        ''}];
end

function s = pStr(p)
    if p < .001
        s = '< .001';
    else
        s = ['= ' regexprep(sprintf('%.3f', p), '^0\.', '.')];
    end
end

% ======================================================================= %
%  String-escaping helpers (see generateQuartoReport.m's own copies of
%  these -- duplicated rather than shared, both local-only there too)
% ======================================================================= %
function s = rLit(matlabText)
    s = strrep(char(matlabText), '\', '\\');
    s = strrep(s, '"', '\"');
end

function s = mdLit(matlabText)
    s = char(matlabText);
    special = {'\', '*', '_', '#', '[', ']', '`', '<', '>'};
    for i = 1:numel(special)
        s = strrep(s, special{i}, ['\' special{i}]);
    end
end

function lines = nullDistributionLines()
%NULLDISTRIBUTIONLINES  The permutation null distribution, with the observed
%   cluster masses marked on it.
%
%   THE TEST MADE VISIBLE. A cluster-based permutation test compares one
%   number -- a cluster's mass, the summed statistic over its points --
%   against the distribution of that same number under relabelling. Every
%   other figure in this report shows WHERE and WHEN an effect was; this
%   one shows the comparison the p-value actually came from. Without it a
%   reader is asked to take "p = .03" on trust.
%
%   What it answers at a glance: how far into the tail the observed cluster
%   sits, whether the null is tight or broad, and -- the question a single
%   p-value cannot address -- whether the largest cluster is exceptional or
%   merely the largest of several similar ones.
%
%   Absent for TFCE, which scores each point by the support it gathers
%   across thresholds rather than forming discrete clusters, so there is no
%   cluster mass and no distribution of one. The section says so instead of
%   drawing an empty panel.
    lines = ReportDoc.lines({ ...
        ReportDoc.template('cs-null-distribution.qmd') ...
        ['A cluster-level *p*-value indicates that an effect exists somewhere within the ' ...
         'cluster. It ' ...
         'is not a statement about the cluster''s boundaries: its extent in time and across ' ...
         'channels is a property of the threshold and the data together, so the onset, offset ' ...
         'and topography visible above should not be read as estimates of when or where the ' ...
         'effect begins and ends (Sassenhagen & Draschkow, 2019).'] ...
        '' ''});
end
