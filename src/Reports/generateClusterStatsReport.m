function qmdText = generateClusterStatsReport(summary, statCsvName, waveformCsvName, outlineCsvName, nullCsvName)
%GENERATECLUSTERSTATSREPORT  A Quarto (.qmd) report for one ClusterStats()
%   result: rendering it (self-contained HTML) produces narrative prose
%   explaining the test that ran, a summary table of every cluster found,
%   an overview heatmap of the test statistic across the whole channel x
%   time grid, and, for the strongest few clusters, a topographic plot
%   (where) and a time-course plot (when) each.
%
%   Unlike generateQuartoReport.m (whose R code runs the actual
%   statistical tests, since rstatix/lme4/etc. can do that from a flat
%   CSV), the cluster-permutation test itself has ALREADY run in MATLAB
%   by the time this is called -- FieldTrip is a MATLAB toolbox, R has no
%   equivalent -- so this report's own R code only narrates and PLOTS a
%   precomputed result; SUMMARY (see ClusterStats.m) supplies every number
%   it narrates, and STATCSVNAME/WAVEFORMCSVNAME/OUTLINECSVNAME (bare
%   filenames, resolved relative to the .qmd's own folder -- see
%   exportClusterStatsCSVs.m) supply what it plots.
%
%   Requires the R packages tidyverse and gt (auto-installed by the
%   report's own setup chunk on first render, same as
%   generateQuartoReport.m) plus a working Quarto installation to actually
%   render the .qmd this function returns into HTML.
%
%   See also EXPORTCLUSTERSTATSCSVS, CLUSTERSTATS, ALAKAZAM.ONCLUSTERSTATS.
    lines = [ ...
        preambleLines(summary, statCsvName, waveformCsvName, outlineCsvName, nullCsvName), ...
        introLines(summary), ...
        summaryTableLines(), ...
        heatmapLines(), ...
        nullDistributionLines(), ...
        clusterDetailLines(summary)];
    qmdText = strjoin(lines, newline);
end

% ======================================================================= %
%  Preamble
% ======================================================================= %
function lines = preambleLines(summary, statCsvName, waveformCsvName, outlineCsvName, nullCsvName)
    lines = ReportDoc.lines([ReportDoc.yamlHeader('Alakazam Cluster Statistics Report'), { ...
        ReportDoc.template('cs-setup.Rpart') ...
        }, ReportDoc.packageBootstrap({'tidyverse', 'gt'}), { ...
        '' ...
        sprintf('stat_df     <- read_csv("%s", show_col_types = FALSE)', rLit(statCsvName)) ...
        sprintf('waveform_df <- read_csv("%s", show_col_types = FALSE)', rLit(waveformCsvName)) ...
        sprintf('outline_df  <- read_csv("%s", show_col_types = FALSE)', rLit(outlineCsvName)) ...
        sprintf('null_file   <- "%s"', rLit(nullCsvName)) ...
        'null_df     <- if (file.exists(null_file)) read_csv(null_file, show_col_types = FALSE) else NULL' ...
        '' ...
        }, ReportDoc.apaHelpers(), { ...
        '```' ...
        ''}]);
end

% ======================================================================= %
%  Intro narrative
% ======================================================================= %
function lines = introLines(summary)
    nSig = sum([summary.clusters.significant]);
    lines = { ...
        '## Cluster Statistics' ...
        '' ...
        sprintf('%s', mdLit(contrastSentence(summary.contrast))) ...
        '' ...
        sprintf('Tested across %d subject(s), %s permutation(s), %s.', ...
            summary.nSubjects, permutationLabel(summary.opts.numrandomization), ...
            correctionSentence(summary.opts)) ...
        '' ...
        sprintf(['%d cluster(s) were found (positive and negative together); %d were significant ' ...
            'at %s.'], numel(summary.clusters), nSig, alphaClause(summary.opts.alpha)) ...
        '' ...
        ['This is a whole-scalp, whole-epoch test: unlike a pre-chosen channel/window ' ...
         'analysis, it does not assume in advance where or when an effect should appear. ' ...
         'A **cluster** is a contiguous group of (channel, time) points that all crossed the ' ...
         'cluster-forming threshold in the same direction; its own p-value comes from comparing ' ...
         'its summed test statistic against a null distribution built by repeatedly shuffling ' ...
         'condition/group labels and re-running the same clustering procedure, so it already ' ...
         'accounts for having tested every channel and time point at once, rather than needing a ' ...
         'separate per-comparison correction.'] ...
        '' ...
        ['**What a significant cluster licenses you to say.** That the conditions differ ' ...
         'somewhere in the space that was tested, at the *p*-value reported for that cluster, ' ...
         'already corrected for having looked everywhere at once. That the difference ran in ' ...
         'the cluster''s own direction, since its sign is the sign of the statistic that built ' ...
         'it. And, as plain description of this dataset rather than as inference, which ' ...
         'channels and times it covered.'] ...
        '' ...
        ['**What buys back a claim about where or when** is restricting the test in advance. ' ...
         'A test run over one window and one set of channels has that window and those ' ...
         'channels as its hypothesis, so a significant result there *is* the statement that an ' ...
         'effect exists in them. Localisation comes from choosing the space before looking, ' ...
         'not from reading the boundaries of a cluster afterwards; the two routes answer ' ...
         'different questions and this report answers the second.'] ...
        '' ...
        ['A cluster that is **not** significant is not evidence that the conditions do not ' ...
         'differ, and no individual (channel, time) point inside a significant cluster is ' ...
         'itself protected: the correction is for the test as a whole.'] ...
        ''};
end

function s = contrastSentence(contrast)
    switch contrast.mode
        case 'vsZero'
            s = sprintf('Bin "%s" was tested against zero, within subjects.', contrast.bin);
        case 'paired'
            s = sprintf('Bin "%s" was tested against bin "%s", within subjects (paired).', ...
                contrast.binA, contrast.binB);
        case 'independent'
            s = sprintf('Bin "%s" was tested between two groups (independent samples).', contrast.bin);
    end
end

function s = correctionSentence(opts)
%CORRECTIONSENTENCE  How the test was corrected, naming only the thresholds
%   that actually applied to it.
%
%   TFCE HAS NO CLUSTER-FORMING THRESHOLD. Not choosing one is the whole
%   reason to use it (see ClusterStats' own options: clusteralpha is ignored
%   for 'tfce'), so printing the unused value beside it described a test that
%   was never run, and invited a reader to report a threshold that had no
%   effect on the result.
%
%   THE BACKSLASH BEFORE alpha IS DOUBLED HERE AND MUST NOT BE ANYWHERE ELSE.
%   These are sprintf FORMAT strings, where \\ emits one backslash (and a lone
%   \a would emit a BEL character, not the letters). The bug this replaces had
%   the same '$\\alpha$' as a sprintf ARGUMENT instead, substituted through a
%   %s, where nothing unescapes anything: both backslashes reached the Quarto
%   and LaTeX printed \alpha as text rather than the letter.
    if strcmpi(opts.correctm, 'tfce')
        s = sprintf(['TFCE correction (no cluster-forming threshold is chosen, which is what ' ...
            'TFCE is for; significance at $\\alpha$ = %s)'], numToStr(opts.alpha));
    else
        s = sprintf('cluster correction (cluster-forming *p* < %s, cluster-level $\\alpha$ = %s)', ...
            numToStr(opts.clusteralpha), numToStr(opts.alpha));
    end
end

function s = alphaClause(alpha)
    s = sprintf('*p* < %s', numToStr(alpha));
end

function s = numToStr(x)
    s = regexprep(sprintf('%.4g', x), '^0\.', '.');
end

function s = permutationLabel(numrandomization)
%PERMUTATIONLABEL  NUMRANDOMIZATION for narration -- a plain count, or
%   "all (exhaustive)" when ClusterStats.resolveNumRandomization upgraded
%   it to FieldTrip's own 'all' (an exhaustive 2^N sign-flip enumeration,
%   not a number of randomizations to pass through %d, which would
%   otherwise print each character of "all" as its own code point).
    if ischar(numrandomization) || isstring(numrandomization)
        s = 'all (exhaustive)';
    else
        s = sprintf('%d', numrandomization);
    end
end

