        '  d <- grp %>% filter(channel == ch, !is.na(value)) %>% droplevels()' ...
        '  if (n_distinct(d$dataset) < 2 || n_distinct(d$group) < 2) {' ...
        '    cat(sprintf("\n\n### %s\n\n*Skipped: fewer than two subjects, or fewer than two groups, have a usable value for this channel.*\n\n", ch))' ...
