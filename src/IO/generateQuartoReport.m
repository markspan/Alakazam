function block = pairedSection(windowLabel, measureType, bin1, bin2)
%PAIREDSECTION  Exactly two ordinary bins: paired t-test + Cohen's dz,
%   with a Wilcoxon signed-rank robustness check.
    lines = { ...
        '## __WINDOW_MD__ -- __MEASURETYPE_MD__' ...
        '' ...
        'Two conditions: "__BIN1_MD__" vs. "__BIN2_MD__".' ...
        '' ...
        '```{r}' ...
        '#| label: __CHUNKLABEL__' ...
        '#| results: asis' ...
        'grp <- dat %>% filter(measure_type == "__MEASURETYPE_R__", window == "__WINDOW_R__",' ...
        '                       bin %in% c("__BIN1_R__", "__BIN2_R__")) %>% droplevels()' ...
        '__BLOCKMATCHDIAGNOSTIC__' ...
        '' ...
        'for (ch in unique(grp$channel)) {' ...
        '  # The whole per-channel body is one tryCatch: an unanticipated' ...
        '  # error on ONE channel would otherwise abort this entire chunk --' ...
        '  # and, since Quarto halts the whole render on any chunk error,' ...
        '  # every section after it too -- rather than just costing this one' ...
        '  # channel''s own results.' ...
        '  tryCatch({' ...
        '  # !is.na(value) first: a subject missing ONE of the two bins''' ...
        '  # values (e.g. a peak-finding failure) then correctly fails the' ...
        '  # n == 2 check below rather than being counted as present with a' ...
        '  # value the tests below cannot use.' ...
        '  d0 <- grp %>% filter(channel == ch, !is.na(value)) %>% droplevels()' ...
        '  counts <- d0 %>% count(dataset)' ...
        '  keep <- counts %>% filter(n == 2) %>% pull(dataset)' ...
        '  d <- d0 %>% filter(dataset %in% keep) %>% droplevels()' ...
        '  if (n_distinct(d$dataset) < 2) {' ...
        '    counts_txt <- paste(sprintf("%s (n=%d)", counts$dataset, counts$n), collapse = ", ")' ...
        '    cat(sprintf("\n\n### %s\n\n*Skipped: only %d of %d subject(s) with any non-missing value have BOTH bins present (at least 2 are needed). Rows per subject for this channel: %s.*\n\n",' ...
        '                ch, length(keep), n_distinct(d0$dataset), counts_txt))' ...
        '    next' ...
        '  }' ...
        '  tag <- str_replace_all(paste("__WINDOW_R__", "__MEASURETYPE_R__", ch, sep = "_"), "[^A-Za-z0-9]+", "_")' ...
        '' ...
        '  wide <- d %>% select(dataset, bin, value) %>% pivot_wider(names_from = bin, values_from = value)' ...
        '  diffs <- wide[["__BIN2_R__"]] - wide[["__BIN1_R__"]]' ...
        '  # Base R''s shapiro.test(), not rstatix''s shapiro_test(): the latter''s' ...
        '  # tidied $p column is only reliable for its GROUPED (data %>%' ...
        '  # group_by() %>% shapiro_test()) form -- called on a bare vector it can' ...
        '  # come back without a $p column at all. Base shapiro.test() has a' ...
        '  # stable list return ($statistic, $p.value); tryCatch handles the' ...
        '  # genuine edge cases it errors on outright (n < 3, zero variance)' ...
        '  # rather than relying on any particular empty-result shape.' ...
        '  shap <- tryCatch(shapiro.test(diffs), error = function(e) NULL)' ...
        '  tt <- t.test(wide[["__BIN2_R__"]], wide[["__BIN1_R__"]], paired = TRUE)' ...
        '  dz <- d %>% cohens_d(value ~ bin, paired = TRUE)' ...
        '  wt <- wilcox.test(wide[["__BIN2_R__"]], wide[["__BIN1_R__"]], paired = TRUE)' ...
        '' ...
        '  cat(sprintf("\n\n### %s\n\n", ch))' ...
        '  descr <- d %>% group_by(bin) %>% summarise(M = mean(value), SD = sd(value), n = n(), .groups = "drop")' ...
        '  cat(as_raw_html(apa_gt(descr, "Descriptive Statistics")))' ...
        '' ...
        '  if (is.null(shap)) {' ...
        '    cat("\nNormality of the paired differences could not be assessed (fewer than 3 usable observations, or no variability among them).\n\n")' ...
        '  } else {' ...
        '    normal_txt <- if (shap$p.value >= .05) "did not depart from normality" else "departed from normality (consider the Wilcoxon test below)"' ...
        '    cat(sprintf("\nA Shapiro-Wilk test indicated the paired differences %s, *W* = %s, *p* %s.\n\n",' ...
        '                normal_txt, apa_num(unname(shap$statistic)), apa_p(shap$p.value)))' ...
        '  }' ...
        '' ...
        '  sig_txt <- if (tt$p.value < .05) "a significant" else "no significant"' ...
        '  cat(sprintf("\nA paired-samples *t*-test found %s difference between __BIN1_MD__ and __BIN2_MD__,\n", sig_txt))' ...
        '  cat(sprintf("*t*(%d) = %s, *p* %s, Cohen''s *d~z~* = %s (%s). A Wilcoxon signed-rank test, run\n",' ...
        '              round(tt$parameter), apa_num(tt$statistic), apa_p(tt$p.value), apa_num(dz$effsize), dz$magnitude))' ...
        '  cat(sprintf("as a robustness check alongside it, gave *V* = %s, *p* %s.\n\n", apa_num(wt$statistic), apa_p(wt$p.value)))' ...
        '' ...
        '  omnibus <- bind_rows(omnibus, tibble(group = tag, design = "paired_t", test = "paired_t_test", p = tt$p.value))' ...
        '' ...
        '  p <- ggplot(d, aes(bin, value)) +' ...
        '    geom_violin(fill = "#4a7fc9", alpha = 0.15, colour = "#4a7fc9", trim = FALSE, linewidth = 0.4) +' ...
        '    geom_line(aes(group = dataset), colour = "grey75", alpha = 0.5) +' ...
        '    geom_point(colour = "grey40", size = 1.4, alpha = 0.5, position = position_jitter(width = 0.04, height = 0)) +' ...
        '    stat_summary(fun = mean, geom = "point", size = 2.2, colour = "#4a7fc9") +' ...
        '    stat_summary(fun.data = mean_se, geom = "errorbar", width = 0.12, colour = "#4a7fc9") +' ...
        '    labs(x = "Bin", y = "__YLABEL__") +' ...
        '    theme_pubr()' ...
        '  print(p)' ...
        '  }, error = function(e) {' ...
        '    cat(sprintf("\n\n### %s\n\n*Could not be analysed: %s*\n\n", ch, conditionMessage(e)))' ...
        '  })' ...
        '}' ...
        '```' ...
        };
    text = strjoin(lines, newline);
    text = strrep(text, '__CHUNKLABEL__', chunkLabel('paired', windowLabel, measureType));
    text = strrep(text, '__YLABEL__', yAxisLabel(measureType));
    text = strrep(text, '__BLOCKMATCHDIAGNOSTIC__', blockMatchDiagnosticText());
    block = fillCommonTokens(text, windowLabel, measureType, bin1, bin2);
end

function block = anovaSection(windowLabel, measureType, binLabels)
%ANOVASECTION  Three or more ordinary bins: repeated-measures ANOVA
%   (Type III) + Holm-corrected pairwise paired t-tests + Cohen's dz per
%   pair, with a Friedman test robustness check.
    binVectorR = strjoin(cellfun(@(b) ['"' rLit(b) '"'], binLabels, 'UniformOutput', false), ', ');
    binListMd = strjoin(cellfun(@(b) mdLit(b), binLabels, 'UniformOutput', false), ', ');
    lines = { ...
        '## __WINDOW_MD__ -- __MEASURETYPE_MD__' ...
        '' ...
        ['__NBINS__ conditions: ' binListMd '.'] ...
        '' ...
        '```{r}' ...
        '#| label: __CHUNKLABEL__' ...
        '#| results: asis' ...
        'grp <- dat %>% filter(measure_type == "__MEASURETYPE_R__", window == "__WINDOW_R__",' ...
        ['                       bin %in% c(' binVectorR ')) %>% droplevels()'] ...
        '__BLOCKMATCHDIAGNOSTIC__' ...
        '' ...
        'for (ch in unique(grp$channel)) {' ...
        '  # The whole per-channel body is one tryCatch: an unanticipated' ...
        '  # error on ONE channel would otherwise abort this entire chunk --' ...
        '  # and, since Quarto halts the whole render on any chunk error,' ...
        '  # every section after it too -- rather than just costing this one' ...
        '  # channel''s own results.' ...
        '  tryCatch({' ...
        '  # !is.na(value) first: a subject missing even one bin''s value' ...
        '  # (e.g. a peak-finding failure, or an unresolved combination bin)' ...
        '  # then correctly fails the below n == n_distinct(bin) check rather' ...
        '  # than being counted as present with a value the tests cannot use.' ...
        '  d0 <- grp %>% filter(channel == ch, !is.na(value)) %>% droplevels()' ...
        '  n_bins_expected <- n_distinct(d0$bin)' ...
        '  counts <- d0 %>% count(dataset)' ...
        '  keep <- counts %>% filter(n == n_bins_expected) %>% pull(dataset)' ...
        '  d <- d0 %>% filter(dataset %in% keep) %>% droplevels()' ...
        '  if (n_distinct(d$dataset) < 2) {' ...
        '    counts_txt <- paste(sprintf("%s (n=%d)", counts$dataset, counts$n), collapse = ", ")' ...
        '    cat(sprintf("\n\n### %s\n\n*Skipped: only %d of %d subject(s) with any non-missing value have all %d bins present (at least 2 are needed). Rows per subject for this channel: %s.*\n\n",' ...
        '                ch, length(keep), n_distinct(d0$dataset), n_bins_expected, counts_txt))' ...
        '    next' ...
        '  }' ...
        '  tag <- str_replace_all(paste("__WINDOW_R__", "__MEASURETYPE_R__", ch, sep = "_"), "[^A-Za-z0-9]+", "_")' ...
        '' ...
        '  cat(sprintf("\n\n### %s\n\n", ch))' ...
        '  descr <- d %>% group_by(bin) %>% summarise(M = mean(value), SD = sd(value), n = n(), .groups = "drop")' ...
        '  cat(as_raw_html(apa_gt(descr, "Descriptive Statistics")))' ...
        '' ...
        '  # Per-bin, not rstatix''s grouped shapiro_test(): that pipeline' ...
        '  # (group_by %>% shapiro_test, via doo()/map()) does not catch a' ...
        '  # per-group failure -- one bin with fewer than 3 usable values' ...
        '  # aborts the WHOLE mutate()/map() call, not just that bin''s row,' ...
        '  # which crashes this entire chunk (and halts the whole render).' ...
        '  # group_modify + tryCatch isolates each bin''s own test instead.' ...
        '  shap <- d %>% group_by(bin) %>% group_modify(~ {' ...
        '    st <- tryCatch(shapiro.test(.x$value), error = function(e) NULL)' ...
        '    if (is.null(st)) tibble(statistic = NA_real_, p = NA_real_)' ...
        '    else tibble(statistic = unname(st$statistic), p = st$p.value)' ...
        '  }) %>% ungroup()' ...
        '  if (any(is.na(shap$p))) {' ...
        '    cat(sprintf("\nNormality could not be assessed for: %s (fewer than 3 usable observations, or no variability among them).\n\n",' ...
        '                paste(shap$bin[is.na(shap$p)], collapse = ", ")))' ...
        '  }' ...
        '  if (all(shap$p >= .05, na.rm = TRUE)) {' ...
        '    cat("\nShapiro-Wilk tests indicated no departure from normality in any assessable condition (all *p*s > .05).\n\n")' ...
        '  } else if (any(shap$p < .05, na.rm = TRUE)) {' ...
        '    cat(sprintf("\nShapiro-Wilk tests indicated a departure from normality in at least one condition (%s);\n",' ...
        '                paste(shap$bin[!is.na(shap$p) & shap$p < .05], collapse = ", ")))' ...
        '    cat("the Friedman test below should be considered alongside the ANOVA.\n\n")' ...
        '  }' ...
        '' ...
        '  aov <- tryCatch(anova_test(data = d, dv = value, wid = dataset, within = bin), error = function(e) NULL)' ...
        '  p_bin <- NA_real_' ...
        '  if (!is.null(aov)) {' ...
        '    tab <- get_anova_table(aov)' ...
        '    if ("bin" %in% tab$Effect) {' ...
        '      binRow <- tab[tab$Effect == "bin", ][1, ]' ...
        '      p_bin <- binRow$p' ...
        '      sig_txt <- if (p_bin < .05) "a significant" else "no significant"' ...
        '      cat(sprintf("\nA repeated-measures ANOVA (Type III sum of squares) revealed %s effect of bin,\n", sig_txt))' ...
        '      cat(sprintf("*F*(%s, %s) = %s, *p* %s, generalized eta-squared = %s.\n\n",' ...
        '                  binRow$DFn, binRow$DFd, apa_num(binRow$F), apa_p(p_bin), apa_num(binRow$ges, 3)))' ...
        '    }' ...
        '    cat(as_raw_html(apa_gt(as.data.frame(tab), "Repeated-Measures ANOVA (Type III)")))' ...
        '  }' ...
        '' ...
        '  pw   <- d %>% pairwise_t_test(value ~ bin, paired = TRUE, p.adjust.method = "holm")' ...
        '  pw_d <- d %>% cohens_d(value ~ bin, paired = TRUE)' ...
        '  sig_pw <- pw %>% left_join(pw_d, by = c("group1", "group2"), suffix = c("", ".d")) %>% filter(p.adj < .05)' ...
        '  if (nrow(sig_pw) > 0) {' ...
        '    pair_txt <- sprintf("%s vs. %s, *p* %s, Cohen''s *d~z~* = %s (%s)",' ...
        '                        sig_pw$group1, sig_pw$group2, apa_p(sig_pw$p.adj), apa_num(sig_pw$effsize), sig_pw$magnitude)' ...
        '    cat(sprintf("\nHolm-corrected pairwise comparisons showed significant differences between: %s.\n\n",' ...
        '                paste(pair_txt, collapse = "; ")))' ...
        '  } else {' ...
        '    cat("\nNo pairwise comparison survived Holm correction.\n\n")' ...
        '  }' ...
        '  cat(as_raw_html(apa_gt(pw, "Pairwise Comparisons (Holm-Corrected)")))' ...
        '' ...
        '  fr <- tryCatch(friedman_test(data = d, value ~ bin | dataset), error = function(e) NULL)' ...
        '  if (!is.null(fr)) {' ...
        '    sig_txt <- if (fr$p < .05) "was significant" else "was not significant"' ...
        '    cat(sprintf("\nA Friedman test, run as a rank-based robustness check, %s, chi-squared(%s) = %s, *p* %s.\n\n",' ...
        '                sig_txt, fr$df, apa_num(fr$statistic), apa_p(fr$p)))' ...
        '  }' ...
        '' ...
        '  omnibus <- bind_rows(omnibus, tibble(group = tag, design = "rm_anova", test = "omnibus", p = p_bin))' ...
        '' ...
        '  pw_xy <- pw %>% add_xy_position(x = "bin")' ...
        '  p <- ggplot(d, aes(bin, value)) +' ...
        '    geom_violin(fill = "#4a7fc9", alpha = 0.15, colour = "#4a7fc9", trim = FALSE, linewidth = 0.4) +' ...
        '    geom_line(aes(group = dataset), colour = "grey75", alpha = 0.5) +' ...
        '    geom_point(colour = "grey40", size = 1.4, alpha = 0.5, position = position_jitter(width = 0.04, height = 0)) +' ...
        '    stat_summary(fun = mean, geom = "point", size = 2.2, colour = "#4a7fc9") +' ...
        '    stat_summary(fun.data = mean_se, geom = "errorbar", width = 0.12, colour = "#4a7fc9") +' ...
        '    stat_pvalue_manual(pw_xy, hide.ns = TRUE, tip.length = 0.01) +' ...
        '    labs(x = "Bin", y = "__YLABEL__") +' ...
        '    theme_pubr()' ...
        '  print(p)' ...
        '  }, error = function(e) {' ...
        '    cat(sprintf("\n\n### %s\n\n*Could not be analysed: %s*\n\n", ch, conditionMessage(e)))' ...
        '  })' ...
        '}' ...
        '```' ...
        };
    text = strjoin(lines, newline);
    text = strrep(text, '__NBINS__', num2str(numel(binLabels)));
    text = strrep(text, '__CHUNKLABEL__', chunkLabel('anova', windowLabel, measureType));
    text = strrep(text, '__YLABEL__', yAxisLabel(measureType));
    text = strrep(text, '__BLOCKMATCHDIAGNOSTIC__', blockMatchDiagnosticText());
    block = fillCommonTokens(text, windowLabel, measureType, '', '');
end

function block = betweenSection(windowLabel, measureType, binLabel)
%BETWEENSECTION  Exactly one ordinary bin, but a between-subjects group is
%   assigned (see WorkSpace.editGroups/distinctGroups) -- so, unlike
%   descriptiveSection's own single-bin, no-comparison-possible case,
%   there IS a comparison here: independent-samples across groups.
%   n_distinct(d$group) is checked PER CHANNEL at R runtime, not decided
%   once in MATLAB (unlike ordinaryLabels/comboBins), since it can
%   legitimately vary channel to channel once NA values are dropped -- an
%   independent-samples *t*-test (2 groups) or a one-way ANOVA + Tukey
%   post-hoc (3+ groups), mirroring pairedSection/anovaSection's own
%   split for the WITHIN-subjects case one bin count up.
    lines = { ...
        '## __WINDOW_MD__ -- __MEASURETYPE_MD__ (Between Subjects)' ...
        '' ...
        'Single condition ("__BIN1_MD__"), compared BETWEEN the between-subjects groups.' ...
        '' ...
        '```{r}' ...
        '#| label: __CHUNKLABEL__' ...
        '#| results: asis' ...
        'grp <- dat %>% filter(measure_type == "__MEASURETYPE_R__", window == "__WINDOW_R__", bin == "__BIN1_R__") %>% droplevels()' ...
        '__BLOCKMATCHDIAGNOSTIC__' ...
        '' ...
        'for (ch in unique(grp$channel)) {' ...
        '  # See descriptiveSection''s own comment on this same tryCatch/next' ...
        '  # pattern: one channel''s failure must not abort the whole render.' ...
        '  tryCatch({' ...
        '  d <- grp %>% filter(channel == ch, !is.na(value)) %>% droplevels()' ...
        '  n_groups <- n_distinct(d$group)' ...
        '  if (n_groups < 2 || nrow(d) < 2) {' ...
        '    cat(sprintf("\n\n### %s\n\n*Skipped: fewer than two groups have a usable value for this channel.*\n\n", ch))' ...
        '    next' ...
        '  }' ...
        '  tag <- str_replace_all(paste("__WINDOW_R__", "__MEASURETYPE_R__", ch, sep = "_"), "[^A-Za-z0-9]+", "_")' ...
        '' ...
        '  cat(sprintf("\n\n### %s\n\n", ch))' ...
        '  descr <- d %>% group_by(group) %>% summarise(M = mean(value), SD = sd(value), n = n(), .groups = "drop")' ...
        '  cat(as_raw_html(apa_gt(descr, "Descriptive Statistics")))' ...
        '' ...
        '  if (n_groups == 2) {' ...
        '    tt <- t.test(value ~ group, data = d)' ...
        '    dcohen <- d %>% cohens_d(value ~ group)' ...
        '    wt <- wilcox.test(value ~ group, data = d)' ...
        '' ...
        '    sig_txt <- if (tt$p.value < .05) "a significant" else "no significant"' ...
        '    cat(sprintf("\nA Welch two-sample *t*-test (unequal variances assumed) found %s difference\n", sig_txt))' ...
        '    cat(sprintf("between groups, *t*(%s) = %s, *p* %s, Cohen''s *d* = %s (%s). A Mann-Whitney\n",' ...
        '                apa_num(tt$parameter, 1), apa_num(tt$statistic), apa_p(tt$p.value), apa_num(dcohen$effsize), dcohen$magnitude))' ...
        '    cat(sprintf("*U* test, run as a robustness check alongside it, gave *W* = %s, *p* %s.\n\n",' ...
        '                apa_num(wt$statistic), apa_p(wt$p.value)))' ...
        '' ...
        '    omnibus <- bind_rows(omnibus, tibble(group = tag, design = "indep_t", test = "welch_t_test", p = tt$p.value))' ...
        '  } else {' ...
        '    aov <- tryCatch(anova_test(data = d, dv = value, between = group), error = function(e) NULL)' ...
        '    p_grp <- NA_real_' ...
        '    if (!is.null(aov)) {' ...
        '      tab <- get_anova_table(aov)' ...
        '      p_grp <- tab$p[1]' ...
