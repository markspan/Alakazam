function block = mixedSection(windowLabel, measureType, binLabels)
%MIXEDSECTION  Two or more ordinary bins AND a between-subjects group
%   assigned -- a mixed (split-plot) design: bin is the within-subjects
%   factor (as in anovaSection), group is the between-subjects factor (as
%   in betweenSection), tested together in one rstatix::anova_test(...,
%   within = bin, between = group) call, which reports THREE effects
%   (group, bin, and their interaction) rather than one. Post-hoc follows
%   the standard rstatix mixed-design recipe: pairwise bin comparisons
%   WITHIN each group, and pairwise group comparisons WITHIN each bin --
%   two different questions ("does condition matter for this group",
%   "does group matter for this condition"), not one pairwise table.
%   The interaction's own p-value (not the main effects') is what feeds
%   the cross-report omnibus summary, since the interaction is usually
%   the actually-interesting result in a mixed design (do the groups
%   differ in how they respond to condition), and each section can only
%   contribute one row per channel to keep that summary's own multiple-
%   comparison correction meaningful.
    binVectorR = strjoin(cellfun(@(b) ['"' rLit(b) '"'], binLabels, 'UniformOutput', false), ', ');
    binListMd = strjoin(cellfun(@(b) mdLit(b), binLabels, 'UniformOutput', false), ', ');
    lines = { ...
        '## __WINDOW_MD__ -- __MEASURETYPE_MD__ (Mixed Design)' ...
        '' ...
        ['__NBINS__ conditions: ' binListMd ' -- within subjects, crossed with the between-subjects group.'] ...
        '' ...
        '```{r}' ...
        '#| label: __CHUNKLABEL__' ...
        '#| results: asis' ...
        'grp <- dat %>% filter(measure_type == "__MEASURETYPE_R__", window == "__WINDOW_R__",' ...
        ['                       bin %in% c(' binVectorR ')) %>% droplevels()'] ...
        '__BLOCKMATCHDIAGNOSTIC__' ...
        '' ...
        'for (ch in unique(grp$channel)) {' ...
        '  # See descriptiveSection''s own comment on this same tryCatch/next' ...
        '  # pattern: one channel''s failure must not abort the whole render.' ...
        '  tryCatch({' ...
        '  d0 <- grp %>% filter(channel == ch, !is.na(value)) %>% droplevels()' ...
        '  n_bins_expected <- n_distinct(d0$bin)' ...
        '  counts <- d0 %>% count(dataset)' ...
        '  keep <- counts %>% filter(n == n_bins_expected) %>% pull(dataset)' ...
        '  d <- d0 %>% filter(dataset %in% keep) %>% droplevels()' ...
        '  if (n_distinct(d$dataset) < 2 || n_distinct(d$group) < 2) {' ...
        '    counts_txt <- paste(sprintf("%s (n=%d)", counts$dataset, counts$n), collapse = ", ")' ...
        '    cat(sprintf("\n\n### %s\n\n*Skipped: only %d of %d subject(s) with any non-missing value have all %d bins present, or fewer than two groups remain among them (at least 2 subjects across at least 2 groups are needed). Rows per subject for this channel: %s.*\n\n",' ...
        '                ch, length(keep), n_distinct(d0$dataset), n_bins_expected, counts_txt))' ...
        '    next' ...
        '  }' ...
        '  tag <- str_replace_all(paste("__WINDOW_R__", "__MEASURETYPE_R__", ch, sep = "_"), "[^A-Za-z0-9]+", "_")' ...
        '' ...
        '  cat(sprintf("\n\n### %s\n\n", ch))' ...
        '  descr <- d %>% group_by(group, bin) %>% summarise(M = mean(value), SD = sd(value), n = n(), .groups = "drop")' ...
        '  cat(as_raw_html(apa_gt(descr, "Descriptive Statistics")))' ...
        '' ...
        '  aov <- tryCatch(anova_test(data = d, dv = value, wid = dataset, within = bin, between = group), error = function(e) NULL)' ...
        '  p_int <- NA_real_' ...
        '  if (!is.null(aov)) {' ...
        '    tab <- get_anova_table(aov)' ...
        '    for (eff in c("group", "bin", "group:bin")) {' ...
        '      if (eff %in% tab$Effect) {' ...
        '        effRow <- tab[tab$Effect == eff, ][1, ]' ...
        '        sig_txt <- if (effRow$p < .05) "a significant" else "no significant"' ...
        '        cat(sprintf("\nThe mixed ANOVA revealed %s effect of %s, *F*(%s, %s) = %s, *p* %s,\n",' ...
        '                    sig_txt, eff, effRow$DFn, effRow$DFd, apa_num(effRow$F), apa_p(effRow$p)))' ...
        '        cat(sprintf("generalized eta-squared = %s.\n\n", apa_num(effRow$ges, 3)))' ...
        '        if (eff == "group:bin") p_int <- effRow$p' ...
        '      }' ...
        '    }' ...
        '    cat(as_raw_html(apa_gt(as.data.frame(tab), "Mixed ANOVA (Between: group, Within: bin)")))' ...
        '  }' ...
        '' ...
        '  pwc_within <- d %>% group_by(group) %>% pairwise_t_test(value ~ bin, paired = TRUE, p.adjust.method = "holm") %>% ungroup()' ...
        '  sig_within <- pwc_within %>% filter(p.adj < .05)' ...
        '  if (nrow(sig_within) > 0) {' ...
        '    pair_txt <- sprintf("within %s: %s vs. %s, *p* %s", sig_within$group, sig_within$group1, sig_within$group2, apa_p(sig_within$p.adj))' ...
        '    cat(sprintf("\nHolm-corrected within-group comparisons showed significant differences %s.\n\n",' ...
        '                paste(pair_txt, collapse = "; ")))' ...
        '  } else {' ...
        '    cat("\nNo within-group pairwise comparison survived Holm correction.\n\n")' ...
        '  }' ...
        '  cat(as_raw_html(apa_gt(pwc_within, "Within-Group Pairwise Comparisons (Holm-Corrected)")))' ...
        '' ...
        '  pwc_between <- d %>% group_by(bin) %>% pairwise_t_test(value ~ group, paired = FALSE, p.adjust.method = "holm") %>% ungroup()' ...
        '  sig_between <- pwc_between %>% filter(p.adj < .05)' ...
        '  if (nrow(sig_between) > 0) {' ...
        '    pair_txt <- sprintf("at %s: %s vs. %s, *p* %s", sig_between$bin, sig_between$group1, sig_between$group2, apa_p(sig_between$p.adj))' ...
        '    cat(sprintf("\nHolm-corrected between-group comparisons showed significant differences %s.\n\n",' ...
        '                paste(pair_txt, collapse = "; ")))' ...
        '  } else {' ...
        '    cat("\nNo between-group pairwise comparison survived Holm correction.\n\n")' ...
        '  }' ...
        '  cat(as_raw_html(apa_gt(pwc_between, "Between-Group Pairwise Comparisons (Holm-Corrected)")))' ...
        '' ...
        '  omnibus <- bind_rows(omnibus, tibble(group = tag, design = "mixed_anova", test = "group_x_bin_interaction", p = p_int))' ...
        '' ...
        '  p <- ggplot(d, aes(bin, value, colour = group, fill = group)) +' ...
        '    geom_violin(alpha = 0.15, position = position_dodge(0.7), trim = FALSE, linewidth = 0.4) +' ...
        '    geom_point(alpha = 0.4, size = 1.2, position = position_jitterdodge(jitter.width = 0.08, dodge.width = 0.7)) +' ...
        '    stat_summary(fun = mean, geom = "point", size = 2.2, position = position_dodge(0.7)) +' ...
        '    stat_summary(fun.data = mean_se, geom = "errorbar", width = 0.12, position = position_dodge(0.7)) +' ...
        '    labs(x = "Bin", y = "__YLABEL__", colour = "Group", fill = "Group") +' ...
        '    scale_colour_brewer(palette = "Set2") +' ...
        '    scale_fill_brewer(palette = "Set2") +' ...
        '    theme_pubr()' ...
        '  print(p)' ...
        '  }, error = function(e) {' ...
        '    cat(sprintf("\n\n### %s\n\n*Could not be analysed: %s*\n\n", ch, conditionMessage(e)))' ...
        '  })' ...
        '}' ...
        '```' ...
        };
    text = strjoin(lines, newline);
    text = strrep(text, '__NBINS__', num2str(numel(binLabels)));
    text = strrep(text, '__CHUNKLABEL__', chunkLabel('mixed', windowLabel, measureType));
    text = strrep(text, '__YLABEL__', yAxisLabel(measureType));
    text = strrep(text, '__BLOCKMATCHDIAGNOSTIC__', blockMatchDiagnosticText());
    block = fillCommonTokens(text, windowLabel, measureType, '', '');
end

function tf = isDescriptiveOnlyType(measureType)
%ISDESCRIPTIVEONLYTYPE  True when a combination/difference bin's
%   MEASURETYPE should be reported descriptively only (no one-sample-vs-
%   zero test), for either of two unrelated reasons -- see
%   descriptiveOnlyReason for the matching explanatory text:
%     - A LATENCY (peak_latency, fractional_peak_latency,
%       fractional_area_latency -- ERP measure types): zero has no
%       meaningful interpretation. A combination bin's amplitude/area
%       score has a natural "zero" to test against (no difference between
%       the conditions it combines) -- but its latency does not:
%       Measure.m computes a combination bin's own fractional/peak
%       latency on the DIFFERENCE WAVEFORM itself (bin4's average minus
%       bin3's, say), a genuine point in time, not an arithmetic
%       difference of two separately-measured latencies -- so "is this
%       latency significantly different from 0 ms" has no meaningful
%       null hypothesis behind it.
%     - A CIRCULAR quantity (phase, phaselag -- spectral measure types):
%       an angle that wraps at +/-pi radians, for which ordinary linear
%       statistics (a t-test's own mean/SD) are not valid -- this
%       generator has no circular-statistics machinery to fall back to,
%       so the honest thing is to show the values without a test that
%       would silently misinterpret them near the wrap-around boundary.
%   See comboSection's own header comment for how this changes what gets
%   reported.
    tf = any(strcmp(measureType, {'peak_latency', 'fractional_peak_latency', ...
        'fractional_area_latency', 'phase', 'phaselag'}));
end

function tf = isCircularType(measureType)
%ISCIRCULARTYPE  True for the subset of isDescriptiveOnlyType's own types
%   that are circular specifically (phase, phaselag), not just
%   descriptive-only for the UNRELATED "no meaningful zero" latency
%   reason. The distinction matters once a between-subjects group is
%   assigned (see comboSectionGrouped): a latency has no natural zero to
%   test AGAINST (isDescriptiveOnlyType's own concern), but it is still an
%   ordinary linear quantity, so comparing it BETWEEN groups is perfectly
%   valid -- unlike a circular quantity, for which no linear comparison
%   (one-sample OR between-groups) is valid at all.
    tf = any(strcmp(measureType, {'phase', 'phaselag'}));
end

function s = descriptiveOnlyReason(measureType)
%DESCRIPTIVEONLYREASON  The sentence explaining WHY a descriptive-only
%   combo section (see isDescriptiveOnlyType) skipped its one-sample test
%   -- the specific reason differs between the two categories that
%   function covers, so this is not just a single fixed string.
    if any(strcmp(measureType, {'phase', 'phaselag'}))
        s = ['This is a circular quantity (an angle that wraps at +/-pi radians); the ordinary ' ...
             '(linear) one-sample test used elsewhere in this report is not valid for circular ' ...
             'data, so only descriptive statistics are shown here.'];
    else
        s = ['A latency has no natural "zero" to test against the way an amplitude/area ' ...
             'difference does (zero would mean "no difference"; a latency near 0 ms means ' ...
             'nothing of the kind), so only descriptive statistics are reported here.'];
    end
end

function s = yAxisLabel(measureType)
%YAXISLABEL  A plot's y-axis label for MEASURETYPE. ERP amplitude/area
%   types fall back to the generic "Value": their physical unit (uV or
%   uV.ms) depends on the recording's own calibration, which this
%   generator has no way to know. Every other type (ERP latencies;
%   every Spectral Measure type -- power, amplitude, snr, itc, phase,
%   coherence, phaselag) has a fixed, calibration-independent label, so
%   those are always labelled precisely.
    labels = struct( ...
        'peak_latency',            'Latency (ms)', ...
        'fractional_peak_latency', 'Latency (ms)', ...
        'fractional_area_latency', 'Latency (ms)', ...
        'power',                   'Power', ...
        'amplitude',               'Amplitude', ...
        'snr',                     'SNR', ...
        'itc',                     'ITC', ...
        'phase',                   'Phase (rad)', ...
        'coherence',               'Coherence', ...
        'phaselag',                'Phase lag (rad)');
    if isfield(labels, measureType)
        s = labels.(measureType);
    else
        s = 'Value';
    end
end

function block = comboSection(windowLabel, measureType, comboLabel, recipeText)
%COMBOSECTION  One combination (difference) bin. For most measure types: a
%   one-sample t-test (and Wilcoxon) against zero -- run entirely
%   separately from the omnibus test above, never as one more level
%   within it (see this file's own header comment for why that would be
%   statistically invalid). For a LATENCY or CIRCULAR measure type (see
%   isDescriptiveOnlyType): descriptive statistics only, no test.
    if isDescriptiveOnlyType(measureType)
        block = comboSectionDescriptiveOnly(windowLabel, measureType, comboLabel, recipeText);
        return;
    end
    lines = { ...
        '## __WINDOW_MD__ -- __MEASURETYPE_MD__: __COMBOLABEL_MD__' ...
        '' ...
        'Difference/combination bin "__COMBOLABEL_MD__" (__RECIPE_MD__). Tested against zero, not folded' ...
        'into any omnibus test over the ordinary bins above, since its own scores are a linear' ...
        'combination of the other bins'' scores, not an independent condition.' ...
        '' ...
        '```{r}' ...
        '#| label: __CHUNKLABEL__' ...
        '#| results: asis' ...
        'grp <- dat %>% filter(measure_type == "__MEASURETYPE_R__", window == "__WINDOW_R__", bin == "__COMBOLABEL_R__") %>% droplevels()' ...
        '__BLOCKMATCHDIAGNOSTIC__' ...
        '' ...
        'for (ch in unique(grp$channel)) {' ...
        '  # The whole per-channel body is one tryCatch: an unanticipated' ...
        '  # error on ONE channel would otherwise abort this entire chunk --' ...
        '  # and, since Quarto halts the whole render on any chunk error,' ...
        '  # every section after it too -- rather than just costing this one' ...
        '  # channel''s own results.' ...
        '  tryCatch({' ...
        '  # !is.na(value): a combination bin is left NA per Average.m/Measure.m' ...
        '  # for a subject it could not resolve (see Measure.m''s own header' ...
        '  # comment) without dropping that subject''s row entirely, so' ...
        '  # n_distinct(dataset) below must be counted AFTER this filter, not' ...
        '  # before, or a subject with an unusable NA value still counts as' ...
        '  # "present".' ...
        '  d <- grp %>% filter(channel == ch, !is.na(value))' ...
        '  if (n_distinct(d$dataset) < 2) {' ...
        '    cat(sprintf("\n\n### %s\n\n*Skipped: only %d subject(s) have a non-missing value for this combination bin (at least 2 are needed).*\n\n",' ...
        '                ch, n_distinct(d$dataset)))' ...
        '    next' ...
        '  }' ...
        '  tag <- str_replace_all(paste("__WINDOW_R__", "__MEASURETYPE_R__", "__COMBOLABEL_R__", ch, sep = "_"), "[^A-Za-z0-9]+", "_")' ...
        '' ...
        '  # Base R''s shapiro.test(), not rstatix''s shapiro_test(): the latter''s' ...
        '  # tidied $p column is only reliable for its GROUPED (data %>%' ...
        '  # group_by() %>% shapiro_test()) form -- called on a bare vector it can' ...
        '  # come back without a $p column at all. Base shapiro.test() has a' ...
        '  # stable list return ($statistic, $p.value); tryCatch handles the' ...
        '  # genuine edge cases it errors on outright (n < 3, zero variance)' ...
        '  # rather than relying on any particular empty-result shape.' ...
        '  shap <- tryCatch(shapiro.test(d$value), error = function(e) NULL)' ...
        '  tt <- t.test(d$value, mu = 0)' ...
        '  wt <- wilcox.test(d$value, mu = 0)' ...
        '' ...
        '  cat(sprintf("\n\n### %s\n\n", ch))' ...
        '  descr <- d %>% summarise(M = mean(value), SD = sd(value), n = n())' ...
        '  cat(as_raw_html(apa_gt(descr, "Descriptive Statistics")))' ...
        '' ...
        '  if (is.null(shap)) {' ...
        '    cat("\nNormality of __COMBOLABEL_MD__ could not be assessed (fewer than 3 usable observations, or no variability among them).\n\n")' ...
        '  } else {' ...
        '    normal_txt <- if (shap$p.value >= .05) "did not depart from normality" else "departed from normality (consider the Wilcoxon test below)"' ...
        '    cat(sprintf("\nA Shapiro-Wilk test indicated __COMBOLABEL_MD__ %s, *W* = %s, *p* %s.\n\n",' ...
        '                normal_txt, apa_num(unname(shap$statistic)), apa_p(shap$p.value)))' ...
        '  }' ...
        '' ...
        '  sig_txt <- if (tt$p.value < .05) "differed significantly" else "did not differ significantly"' ...
        '  cat(sprintf("\nA one-sample *t*-test found __COMBOLABEL_MD__ %s from zero, *t*(%d) = %s, *p* %s,\n",' ...
        '              sig_txt, round(tt$parameter), apa_num(tt$statistic), apa_p(tt$p.value)))' ...
        '  cat(sprintf("*M* = %s. A Wilcoxon signed-rank test, run as a robustness check alongside it,\n", apa_num(mean(d$value))))' ...
        '  cat(sprintf("gave *V* = %s, *p* %s.\n\n", apa_num(wt$statistic), apa_p(wt$p.value)))' ...
        '' ...
        '  omnibus <- bind_rows(omnibus, tibble(group = tag, design = "one_sample_vs_0", test = "one_sample_t_test", p = tt$p.value))' ...
        '' ...
        '  p <- ggplot(d, aes(x = 1, y = value)) +' ...
        '    geom_violin(aes(group = 1), fill = "#4a7fc9", alpha = 0.15, colour = "#4a7fc9",' ...
        '                trim = FALSE, linewidth = 0.4, width = 0.6) +' ...
        '    geom_jitter(width = 0.05, colour = "grey40", alpha = 0.6) +' ...
        '    geom_hline(yintercept = 0, linetype = "dashed", colour = "grey50") +' ...
        '    stat_summary(fun = mean, geom = "point", size = 3, colour = "#4a7fc9") +' ...
        '    stat_summary(fun.data = mean_se, geom = "errorbar", width = 0.1, colour = "#4a7fc9") +' ...
        '    labs(x = NULL, y = "__YLABEL__") +' ...
        '    scale_x_continuous(breaks = NULL) +' ...
        '    theme_pubr()' ...
        '  print(p)' ...
        '  }, error = function(e) {' ...
        '    cat(sprintf("\n\n### %s\n\n*Could not be analysed: %s*\n\n", ch, conditionMessage(e)))' ...
        '  })' ...
        '}' ...
        '```' ...
        };
    text = strjoin(lines, newline);
    text = fillToken(text, 'COMBOLABEL', comboLabel);
    text = fillToken(text, 'RECIPE', recipeText);
    text = strrep(text, '__CHUNKLABEL__', chunkLabel('combo', windowLabel, measureType, comboLabel));
    text = strrep(text, '__YLABEL__', yAxisLabel(measureType));
    text = strrep(text, '__BLOCKMATCHDIAGNOSTIC__', blockMatchDiagnosticText());
    block = fillCommonTokens(text, windowLabel, measureType, '', '');
end

