%   assigned -- a mixed (split-plot) design: bin is the within-subjects
%   factor (as in anovaSection), group is the between-subjects factor (as
%   in betweenSection). Like anovaSection, this now fits a linear mixed
%   model (value ~ bin * group, subject random intercept AND slope for
%   bin -- group cannot have a random slope, it is between-subjects, so
%   there is no within-subject variation to fit one against) rather than
%   a mixed ANOVA -- for the same reason: a subject missing one bin used
%   to be dropped from the WHOLE channel, where the LMM instead fits on
%   every non-missing (subject, bin) observation directly. Reports all
%   three fixed-effect tests (group, bin, group:bin -- Satterthwaite df),
%   one overall marginal R^2, standardized coefficients, and model-based
%   Holm-corrected post-hoc via emmeans, split the same two ways the
%   rstatix-based version was: pairwise bin contrasts WITHIN each group,
%   and pairwise group contrasts WITHIN each bin. The interaction's own
%   p-value (not the main effects') is what feeds the cross-report
%   omnibus summary, since the interaction is usually the actually-
%   interesting result in a mixed design (do the groups differ in how
%   they respond to condition), and each section can only contribute one
%   row per channel to keep that summary's own multiple-comparison
%   correction meaningful.
    binVectorR = strjoin(cellfun(@(b) ['"' rLit(b) '"'], binLabels, 'UniformOutput', false), ', ');
    binListMd = strjoin(cellfun(@(b) mdLit(b), binLabels, 'UniformOutput', false), ', ');
    lines = { ...
        '## __WINDOW_MD__ -- __MEASURETYPE_MD__ (Mixed Design)' ...
        '' ...
