function block = comboSectionGrouped(windowLabel, measureType, comboLabel, recipeText, includeVsZero, includeBetweenGroups)
%COMBOSECTIONGROUPED  One combination (difference) bin, WITH a between-
%   subjects group assigned -- the grouped counterpart of comboSection/
%   comboSectionDescriptiveOnly, answering "does patients_group vs.
%   controls_group have a different DIFFERENCE (e.g. priming effect,
%   repetition effect) score", not just "is there a difference at all".
%
%   INCLUDEVSZERO (false for a latency/circular MEASURETYPE, see
%   isDescriptiveOnlyType) controls whether a one-sample-vs-zero test
%   still runs, now once PER GROUP rather than once for the whole sample
%   -- "does this effect exist at all" becomes a per-group question once
%   groups exist, same statistical-validity reasoning as the ungrouped
%   comboSection, just repeated per group.
%
%   INCLUDEBETWEENGROUPS (false only for a CIRCULAR MEASURETYPE, see
%   isCircularType) controls the actually-new comparison this function
%   adds: an independent-samples test of the combo score BETWEEN groups
%   (Welch *t*-test for 2 groups, one-way ANOVA + Tukey for 3+) -- valid
%   for a latency combo bin even though the "vs zero" test above is not
%   (a latency has no natural zero to test AGAINST, but is still an
%   ordinary linear quantity groups can be compared on), invalid only for
%   a circular quantity (phase/phaselag), for which no linear comparison
%   at all -- one-sample or between-groups -- is valid.
    lines = [{ ...
        '## __WINDOW_MD__ -- __MEASURETYPE_MD__: __COMBOLABEL_MD__ (By Group)' ...
        '' ...
        ['Difference/combination bin "__COMBOLABEL_MD__" (__RECIPE_MD__), broken down by the ' ...
         'between-subjects group. __REASON_MD__'] ...
        '' ...
        '```{r}' ...
        '#| label: __CHUNKLABEL__' ...
        '#| results: asis' ...
        'grp <- dat %>% filter(measure_type == "__MEASURETYPE_R__", window == "__WINDOW_R__", bin == "__COMBOLABEL_R__") %>% droplevels()' ...
        '__BLOCKMATCHDIAGNOSTIC__' ...
        '' ...
        'for (ch in unique(grp$channel)) {' ...
        '  # See descriptiveSection''s own comment on this same tryCatch/next' ...
        '  # pattern: one channel''s failure must not abort the whole render.' ...
        '  tryCatch({' ...
        '  d <- grp %>% filter(channel == ch, !is.na(value)) %>% droplevels()' ...
        '  if (n_distinct(d$dataset) < 2) {' ...
        '    cat(sprintf("\n\n### %s\n\n*Skipped: only %d subject(s) have a non-missing value for this combination bin (at least 2 are needed).*\n\n",' ...
        '                ch, n_distinct(d$dataset)))' ...
        '    next' ...
        '  }' ...
        '  tag <- str_replace_all(paste("__WINDOW_R__", "__MEASURETYPE_R__", "__COMBOLABEL_R__", ch, sep = "_"), "[^A-Za-z0-9]+", "_")' ...
        '' ...
        '  cat(sprintf("\n\n### %s\n\n", ch))' ...
        '  descr <- d %>% group_by(group) %>% summarise(M = mean(value), SD = sd(value), n = n(), .groups = "drop")' ...
        '  cat(as_raw_html(apa_gt(descr, "Descriptive Statistics")))'}, ...
        vsZeroLines(includeVsZero), ...
        betweenGroupsLines(includeBetweenGroups), ...
        { ...
        '' ...
        zeroLineStatement(includeVsZero) ...
        '  common_layers <- list(' ...
        '    geom_jitter(width = 0.06, alpha = 0.6),' ...
        '    zero_line,' ...
        '    stat_summary(fun = mean, geom = "point", size = 3),' ...
        '    stat_summary(fun.data = mean_se, geom = "errorbar", width = 0.1),' ...
        '    labs(x = "Group", y = "__YLABEL__"),' ...
        '    scale_colour_brewer(palette = "Set2"),' ...
        '    scale_fill_brewer(palette = "Set2"),' ...
        '    theme_pubr(),' ...
        '    theme(legend.position = "none")' ...
        '  )' ...
        '  p <- ggplot(d, aes(group, value, colour = group, fill = group)) + violin_layers() + common_layers' ...
        '  print(p)' ...
        '  }, error = function(e) {' ...
        '    cat(sprintf("\n\n### %s\n\n*Could not be analysed: %s*\n\n", ch, conditionMessage(e)))' ...
        '  })' ...
        '}' ...
        '```' ...
        }];
    text = strjoin(lines, newline);
    text = fillToken(text, 'COMBOLABEL', comboLabel);
    text = fillToken(text, 'RECIPE', recipeText);
    text = fillToken(text, 'REASON', comboGroupedReason(includeVsZero, includeBetweenGroups));
    text = strrep(text, '__CHUNKLABEL__', chunkLabel('combo-grouped', windowLabel, measureType, comboLabel));
    text = strrep(text, '__YLABEL__', yAxisLabel(measureType));
    text = strrep(text, '__BLOCKMATCHDIAGNOSTIC__', blockMatchDiagnosticText());
    block = fillCommonTokens(text, windowLabel, measureType, '', '');
end

function lines = vsZeroLines(includeVsZero)
%VSZEROLINES  The per-group one-sample-vs-zero test, spliced into
%   comboSectionGrouped when INCLUDEVSZERO -- {} (no-op) otherwise.
    if ~includeVsZero
        lines = {};
        return;
    end
    lines = { ...
        '' ...
        '  # One-sample-vs-zero, once PER GROUP: with groups present, "does' ...
        '  # this effect exist at all" becomes a per-group question -- never' ...
        '  # folded into the between-groups comparison below, which asks a' ...
        '  # different thing (does the effect DIFFER between groups, not' ...
        '  # whether it exists in either one).' ...
        '  vs_zero <- d %>% group_by(group) %>% group_modify(~ {' ...
        '    tt <- tryCatch(t.test(.x$value, mu = 0), error = function(e) NULL)' ...
        '    dz <- tryCatch(.x %>% rstatix::cohens_d(value ~ 1, mu = 0, ci = TRUE, ci.type = "bca", nboot = 200),' ...
        '                   error = function(e) tibble(effsize = NA_real_, conf.low = NA_real_, conf.high = NA_real_))' ...
        '    bf <- tryCatch(as.vector(BayesFactor::ttestBF(x = .x$value, mu = 0)), error = function(e) NA_real_)' ...
        '    if (is.null(tt)) return(tibble(M = mean(.x$value), n = nrow(.x), statistic = NA_real_, df = NA_real_, p = NA_real_,' ...
        '                                    d = NA_real_, d_lo = NA_real_, d_hi = NA_real_, bf = NA_real_))' ...
        '    tibble(M = mean(.x$value), n = nrow(.x), statistic = unname(tt$statistic), df = unname(tt$parameter), p = tt$p.value,' ...
        '           d = dz$effsize, d_lo = dz$conf.low, d_hi = dz$conf.high, bf = bf)' ...
        '  }) %>% ungroup()' ...
        '  for (gi in seq_len(nrow(vs_zero))) {' ...
        '    row <- vs_zero[gi, ]' ...
        '    if (is.na(row$p)) {' ...
        '      cat(sprintf("\nWithin %s, __COMBOLABEL_MD__ could not be tested against zero (fewer than 2 usable observations).\n\n", row$group))' ...
        '    } else {' ...
        '      sig_txt <- if (row$p < .05) "differed significantly" else "did not differ significantly"' ...
        '      cat(sprintf("\nWithin %s, __COMBOLABEL_MD__ %s from zero, *t*(%d) = %s, *p* %s, *M* = %s, Cohen''s\n",' ...
        '                  row$group, sig_txt, round(row$df), apa_num(row$statistic), apa_p(row$p), apa_num(row$M)))' ...
        '      cat(sprintf("*d* = %s, 95%% CI [%s, %s], BF~10~ = %s.\n\n",' ...
        '                  apa_num(row$d), apa_num(row$d_lo), apa_num(row$d_hi), apa_bf(row$bf)))' ...
        '    }' ...
        '  }'};
end

function lines = betweenGroupsLines(includeBetweenGroups)
%BETWEENGROUPSLINES  The actually-new comparison comboSectionGrouped adds:
%   an independent-samples test of the combo score BETWEEN groups --
%   spliced in when INCLUDEBETWEENGROUPS, {} (no-op) otherwise. Mirrors
%   betweenSection's own 2-group-t-test/3+-group-one-way-ANOVA split,
%   just on a combination bin's already-differenced score instead of an
%   ordinary bin's raw one.
    if ~includeBetweenGroups
        lines = {};
        return;
    end
    lines = { ...
        '' ...
        '  n_groups <- n_distinct(d$group)' ...
        '  if (n_groups < 2) {' ...
        '    cat("\n*Only one group has a usable value for this channel; the between-group comparison could not be run.*\n\n")' ...
        '  } else if (n_groups == 2) {' ...
        '    tt <- t.test(value ~ group, data = d)' ...
        '    dcohen <- d %>% rstatix::cohens_d(value ~ group, ci = TRUE, ci.type = "bca", nboot = 200)' ...
        '    bf <- tryCatch(as.vector(BayesFactor::ttestBF(formula = value ~ group, data = as.data.frame(d))),' ...
        '                   error = function(e) NA_real_)' ...
        '    sig_txt <- if (tt$p.value < .05) "a significant" else "no significant"' ...
        '    cat(sprintf("\nA Welch two-sample *t*-test found %s difference in __COMBOLABEL_MD__ between groups,\n", sig_txt))' ...
        '    cat(sprintf("*t*(%s) = %s, *p* %s, Cohen''s *d* = %s (%s), 95%% CI [%s, %s], BF~10~ = %s.\n\n",' ...
        '                apa_num(tt$parameter, 1), apa_num(tt$statistic), apa_p(tt$p.value), apa_num(dcohen$effsize), dcohen$magnitude,' ...
        '                apa_num(dcohen$conf.low), apa_num(dcohen$conf.high), apa_bf(bf)))' ...
        '' ...
        '    omnibus <- bind_rows(omnibus, tibble(group = tag, design = "between_group_combo", test = "welch_t_test", p = tt$p.value,' ...
        '                                          estimate = dcohen$effsize, conf.low = dcohen$conf.low, conf.high = dcohen$conf.high))' ...
        '  } else {' ...
        '    # Welch ANOVA + Games-Howell, not classic ANOVA + Tukey -- see' ...
        '    # betweenSection''s own comment on this same choice.' ...
        '    aov <- tryCatch(welch_anova_test(data = d, formula = value ~ group), error = function(e) NULL)' ...
        '    p_grp <- NA_real_' ...
        '    if (!is.null(aov)) {' ...
        '      p_grp <- aov$p[1]' ...
        '      sig_txt <- if (p_grp < .05) "a significant" else "no significant"' ...
        '      cat(sprintf("\nA Welch one-way ANOVA found %s difference in __COMBOLABEL_MD__ between groups, *F*(%s, %s) = %s, *p* %s.\n\n",' ...
        '                  sig_txt, apa_num(aov$DFn[1], 1), apa_num(aov$DFd[1], 1), apa_num(aov$statistic[1]), apa_p(p_grp)))' ...
        '      cat(as_raw_html(apa_gt(as.data.frame(aov), "Welch One-Way ANOVA")))' ...
        '    }' ...
        '' ...
        '    pw <- d %>% games_howell_test(value ~ group)' ...
        '    sig_pw <- pw %>% filter(p.adj < .05)' ...
        '    if (nrow(sig_pw) > 0) {' ...
        '      pair_txt <- sprintf("%s vs. %s, *p* %s, *M*~diff~ = %s, 95%% CI [%s, %s]",' ...
        '                          sig_pw$group1, sig_pw$group2, apa_p(sig_pw$p.adj),' ...
        '                          apa_num(sig_pw$estimate), apa_num(sig_pw$conf.low), apa_num(sig_pw$conf.high))' ...
        '      cat(sprintf("\nGames-Howell pairwise comparisons showed significant differences between: %s.\n\n",' ...
        '                  paste(pair_txt, collapse = "; ")))' ...
        '    } else {' ...
        '      cat("\nNo pairwise comparison survived the Games-Howell correction.\n\n")' ...
        '    }' ...
        '    cat(as_raw_html(apa_gt(pw, "Pairwise Comparisons (Games-Howell)")))' ...
        '' ...
        '    omnibus <- bind_rows(omnibus, tibble(group = tag, design = "between_group_combo", test = "welch_anova", p = p_grp,' ...
        '                                          estimate = NA_real_, conf.low = NA_real_, conf.high = NA_real_))' ...
        '  }'};
end

function line = zeroLineStatement(includeVsZero)
%ZEROLINESTATEMENT  An R statement assigning ZERO_LINE to the ggplot
%   dashed-zero-line reference layer when a "vs zero" test actually ran
%   (matching comboSection's own unconditional geom_hline -- there is
%   always a "vs zero" test there, since it is only ever called for a
%   non-descriptive-only measure type), or to NULL otherwise -- `p + NULL`
%   is a documented ggplot2 no-op, so the plot built from COMMON_LAYERS
%   below can unconditionally include `zero_line` without needing its own
%   INCLUDEVSZERO branch.
    if includeVsZero
        line = '  zero_line <- geom_hline(yintercept = 0, linetype = "dashed", colour = "grey50")';
    else
        line = '  zero_line <- NULL';
    end
end

function s = comboGroupedReason(includeVsZero, includeBetweenGroups)
%COMBOGROUPEDREASON  The sentence explaining what comboSectionGrouped
%   does and does not test, given which of its two optional parts are
%   included -- see its own header comment for the underlying reasoning.
    if includeVsZero && includeBetweenGroups
        s = ['Tested against zero within each group, and compared BETWEEN groups to see whether ' ...
             'the effect itself differs in size between them.'];
    elseif includeBetweenGroups
        s = ['A latency has no natural zero to test against (so no per-group one-sample test is run), ' ...
             'but is compared BETWEEN groups, to see whether it differs in size between them.'];
    else
        s = ['This is a circular quantity (an angle that wraps at +/-pi radians); the ordinary ' ...
             '(linear) tests used elsewhere in this report are not valid for circular data, so only ' ...
             'descriptive statistics per group are shown here.'];
    end
end

