function qmdText = generateQuartoReport(entries, csvFileName)
%GENERATEQUARTOREPORT  A design-aware Quarto (.qmd) report for an exported
%   measurements CSV: rendering it (self-contained HTML) produces a short,
%   APA-styled results report -- narrative prose with inline-computed
%   statistics, APA-formatted tables (gt), and embedded plots -- rather
%   than a plain R console script. Replaces the earlier generateRScript.m,
%   which this supersedes: same design-aware bin classification and
%   rstatix computations underneath (see this file's own block functions),
%   only the OUTPUT layer changed, from cat()/print() console text to
%   Quarto markdown + APA prose.
%
%   Design (see this file's own block functions for the exact rstatix
%   calls, unchanged from generateRScript.m's own choices):
%     - 1 ordinary bin: descriptive statistics only -- no comparison is
%       possible.
%     - 2 ordinary bins: a paired t-test + Cohen's dz, with a Wilcoxon
%       signed-rank robustness check and a Shapiro-Wilk normality note.
%     - 3+ ordinary bins: a repeated-measures ANOVA (Type III) + Holm-
%       corrected pairwise paired t-tests + Cohen's dz per pair, with a
%       Friedman test robustness check.
%     - Each COMBINATION (difference) bin, separately: a one-sample
%       t-test (and Wilcoxon) against zero -- never folded into the
%       omnibus test above, since a combination bin's scores are a linear
%       combination of the OTHER bins', not an independent condition, so
%       including it there would be statistically invalid.
%   Every block's own key p-value also feeds one final cross-group
%   summary table, BH/FDR-corrected across every channel x window x
%   measure group the export produced, not just within one group's own
%   pairwise tests.
%
%   Unlike an APA manuscript's usual terse, no-explanation results prose,
%   generateRScript.m's own console version also carried short "what does
%   this test mean" explainer text throughout, aimed at a reader learning
%   the statistics alongside the results -- deliberately dropped here:
%   an APA-styled report reads as results prose (a repeated-measures
%   ANOVA revealed a significant effect of bin, F(...) = ..., p = ...),
%   not a statistics tutorial.
%
%   ENTRIES/CSVFILENAME: see generateRScript.m's own header comment for
%   both (unchanged) -- ENTRIES(1).EEG carries the bin/design structure
%   (EEG.bindesc) plus either EEG.measurements (an ERP export -- see
%   measureRowTypes) or EEG.spectralMeasures (a Spectral export -- see
%   spectralBlocks), auto-detected from whichever field is present so
%   both onExportMeasurements and onExportSpectral can call this the same
%   way. CSVFILENAME is the bare file name the report's own read_csv()
%   call references, relative to where the report itself is written.
%
%   Requires the R packages tidyverse, rstatix, ggpubr and gt (auto-
%   installed by the report's own setup chunk on first render) plus a
%   working Quarto installation (https://quarto.org) to actually render
%   the .qmd this function returns into HTML.
%
%   See also EXPORTMEASUREMENTSCSV, EXPORTSPECTRALCSV, MEASUREROWTYPES,
%   MEASUREROWVALUE.
    if isempty(entries)
        throw(MException('Alakazam:generateQuartoReport', ...
            'generateQuartoReport needs at least one Measure result to build a report from.'));
    end
    EEG = entries(1).EEG;
    hasErp      = isfield(EEG, 'measurements') && ~isempty(EEG.measurements);
    hasSpectral = isfield(EEG, 'spectralMeasures') && ~isempty(EEG.spectralMeasures);
    if ~hasErp && ~hasSpectral
        throw(MException('Alakazam:generateQuartoReport', ...
            ['generateQuartoReport needs a dataset with at least one Measure window ' ...
             '(EEG.measurements) or Spectral Measure (EEG.spectralMeasures).']));
    end
    if hasErp
        reportTitle = 'ERP';
        groupColumn = 'window';
        blocks = erpBlocks(EEG);
    else
        reportTitle = 'Spectral';
        groupColumn = 'frequency_label';
        blocks = spectralBlocks(EEG);
    end

    [ordinaryLabels, comboBins] = classifyBins(EEG);

    % Between-subjects grouping (see WorkSpace.editGroups/groupFor): a
    % MATLAB-side decision, not rediscovered per section in R, mirroring
    % how ordinaryLabels/comboBins above are also decided once here rather
    % than per chunk. >= 2 DISTINCT non-blank group labels across the
    % export's own subject entries is what actually activates the
    % between/mixed path below -- a workspace where nobody has been
    % assigned a group (or everybody shares one label) renders exactly as
    % it always has, no opt-in flag needed.
    hasGroups = numel(distinctGroups(entries)) >= 2;

    sections = {};
    for bl = 1:numel(blocks)
        blockLabel = blocks(bl).label;
        types = blocks(bl).measureTypes;
        for ti = 1:numel(types)
            measureType = types{ti};

            if numel(ordinaryLabels) == 1
                if hasGroups
                    sections{end + 1} = betweenSection(blockLabel, measureType, ordinaryLabels{1}); %#ok<AGROW>
                else
                    sections{end + 1} = descriptiveSection(blockLabel, measureType, ordinaryLabels{1}); %#ok<AGROW>
                end
            elseif numel(ordinaryLabels) == 2
                if hasGroups
                    sections{end + 1} = mixedSection(blockLabel, measureType, ordinaryLabels); %#ok<AGROW>
                else
                    sections{end + 1} = pairedSection(blockLabel, measureType, ordinaryLabels{1}, ordinaryLabels{2}); %#ok<AGROW>
                end
            elseif numel(ordinaryLabels) >= 3
                if hasGroups
                    sections{end + 1} = mixedSection(blockLabel, measureType, ordinaryLabels); %#ok<AGROW>
                else
                    sections{end + 1} = anovaSection(blockLabel, measureType, ordinaryLabels); %#ok<AGROW>
                end
            end
            for cb = 1:numel(comboBins)
                if hasGroups
                    % includeVsZero: skip for latency/circular types, same
                    % reason as the no-groups path (isDescriptiveOnlyType).
                    % includeBetweenGroups: skip ONLY for circular types --
                    % unlike the "vs zero" test, an ordinary linear
                    % between-groups comparison (a latency IS on a linear
                    % scale) is perfectly valid for a latency combo bin,
                    % just not for a circular one (see isCircularType).
                    sections{end + 1} = comboSectionGrouped(blockLabel, measureType, ...
                        comboBins(cb).label, comboBins(cb).recipeText, ...
                        ~isDescriptiveOnlyType(measureType), ~isCircularType(measureType)); %#ok<AGROW>
                else
                    sections{end + 1} = comboSection(blockLabel, measureType, ...
                        comboBins(cb).label, comboBins(cb).recipeText); %#ok<AGROW>
                end
            end
        end
    end

    parts = [{preambleText(csvFileName, reportTitle, groupColumn, hasGroups)}, sections, {closingText()}];
    qmdText = char(strjoin(parts, [newline newline]));
end

function labels = distinctGroups(entries)
%DISTINCTGROUPS  Every distinct, non-blank .group value across ENTRIES'
%   own 'subject' rows (a grand_average entry's .group is always '', see
%   collectEntriesWithField, so it never contributes a spurious group of
%   its own here).
    isSubject = strcmp({entries.datasetType}, 'subject');
    subjectGroups = {entries(isSubject).group};
    labels = unique(subjectGroups(~cellfun(@isempty, subjectGroups)));
end

function blocks = erpBlocks(EEG)
%ERPBLOCKS  One block per Measure window, .label/.measureTypes (from
%   measureRowTypes) -- the ERP counterpart of spectralBlocks.
    blocks = struct('label', {}, 'measureTypes', {});
    for w = 1:numel(EEG.measurements)
        win = EEG.measurements{w};
        blocks(end + 1) = struct('label', char(string(win.label)), ...
            'measureTypes', {measureRowTypes(win)}); %#ok<AGROW>
    end
end

function blocks = spectralBlocks(EEG)
%SPECTRALBLOCKS  One block per named frequency in EEG.spectralMeasures,
%   .label/.measureTypes -- the Spectral counterpart of erpBlocks. Every
%   named frequency always carries power/amplitude/snr/itc/phase (see
%   SpectralMeasure.m); coherence/phaselag are additional, only present
%   when that frequency was measured against a reference channel --
%   exactly mirroring exportSpectralCSV.m's own writeEntry, so this can
%   never claim a measure_type the CSV does not actually have a column
%   value for.
    blocks = struct('label', {}, 'measureTypes', {});
    for w = 1:numel(EEG.spectralMeasures)
        m = EEG.spectralMeasures{w};
        types = {'power', 'amplitude', 'snr', 'itc', 'phase'};
        if ~isempty(strtrim(char(string(m.refChannel))))
            types = [types, {'coherence', 'phaselag'}]; %#ok<AGROW>
        end
        blocks(end + 1) = struct('label', char(string(m.label)), 'measureTypes', {types}); %#ok<AGROW>
    end
end

% ======================================================================= %
%  Bin classification -- identical to generateRScript.m's own (the whole
%  point of doing this in MATLAB, not R): EEG.bindesc(b).combo is not
%  recoverable from the flat CSV at all.
% ======================================================================= %
function [ordinaryLabels, comboBins] = classifyBins(EEG)
%CLASSIFYBINS  ORDINARYLABELS (cellstr, real conditions) and COMBOBINS (a
%   struct array, .label/.recipeText, one per DefineBins/Average
%   combination bin) from EEG.bindesc. A dataset with no bindesc at all
%   (an unbinned Average) is treated as one implicit ordinary bin, "1" --
%   csvBinLabel's own fallback for exactly this case, so this matches
%   whatever bin value actually ended up in the CSV.
    comboBins = struct('label', {}, 'recipeText', {});
    if ~isfield(EEG, 'bindesc') || isempty(EEG.bindesc)
        ordinaryLabels = {'1'};
        return;
    end
    bindesc = EEG.bindesc;
    isCombo = false(1, numel(bindesc));
    if isfield(bindesc, 'combo')
        isCombo = ~cellfun(@isempty, {bindesc.combo});
    end
    ordinaryLabels = {bindesc(~isCombo).label};
    for b = find(isCombo)
        comboBins(end + 1) = struct('label', char(string(bindesc(b).label)), ...
            'recipeText', comboRecipeText(bindesc, bindesc(b))); %#ok<AGROW>
    end
end

function txt = comboRecipeText(bindesc, entry)
%COMBORECIPETEXT  A combination bin's own recipe as readable text, e.g.
%   "Rare - Frequent" or "0.5*Left + 0.5*Right" -- entry.combo's own .bin
%   values are referenced bins' .index (Average.m's own convention), not
%   array positions, so they are mapped back to a label via bindesc's own
%   .index field.
    indices = [bindesc.index];
    parts = strings(1, numel(entry.combo));
    for t = 1:numel(entry.combo)
        refLabel = bindesc(indices == entry.combo(t).bin).label;
        coeff = entry.combo(t).coeff;
        if t == 1
            if coeff < 0; sgn = "-"; else; sgn = ""; end
        else
            if coeff < 0; sgn = " - "; else; sgn = " + "; end
        end
        if abs(coeff) == 1
            magTxt = "";
        else
            magTxt = string(sprintf('%.3g*', abs(coeff)));
        end
        parts(t) = sgn + magTxt + string(refLabel);
    end
    txt = char(strjoin(parts, ""));
end

% ======================================================================= %
%  Text assembly: strrep-based token substitution, NOT sprintf -- R's own
%  pipe operator (%>%) is full of literal '%' characters that sprintf
%  would misread as format specifiers, so every section below is built by
%  substituting __TOKEN__ placeholders into a literal template instead.
%  Every label needs TWO escaped forms, since it can appear in two
%  different contexts: __X_MD__ (mdLit-escaped) for Quarto markdown
%  prose/headings, __X_R__ (rLit-escaped) for inside an R string literal
%  in a code chunk -- see fillToken.
% ======================================================================= %
function s = rLit(matlabText)
%RLIT  MATLABTEXT as a safe R double-quoted string literal's INNER text
%   (caller still supplies the surrounding quotes): backslashes and
%   double quotes escaped, so a bin/window label an analyst happened to
%   type with one of those characters cannot break the generated R
%   syntax.
    s = strrep(char(matlabText), '\', '\\');
    s = strrep(s, '"', '\"');
end

function s = mdLit(matlabText)
%MDLIT  MATLABTEXT as safe inline Quarto/Pandoc markdown text: escapes
%   the characters markdown gives special meaning outside a code span
%   (\ * _ # [ ] ` < >), so a bin/window label an analyst happened to
%   type with one of those characters cannot corrupt the rendered
%   heading/prose around it (e.g. turn part of a label into unintended
%   italics, or be swallowed as a raw HTML tag).
    s = char(matlabText);
    special = {'\', '*', '_', '#', '[', ']', '`', '<', '>'};
    for i = 1:numel(special)
        s = strrep(s, special{i}, ['\' special{i}]);
    end
end

function s = labelPiece(matlabText)
%LABELPIECE  MATLABTEXT as a safe, lowercase, hyphenated fragment for a
%   Quarto/knitr chunk label (letters, digits, hyphens only -- unlike
%   R/MATLAB identifiers, a chunk label is not restricted to start with a
%   letter, but IS restricted to have no spaces and no characters knitr
%   would choke on, so this is deliberately more conservative than
%   strictly required). Never empty (falls back to "x"), so a blank
%   window/measure-type piece never collapses two different labels into
%   the same "--" run.
    s = lower(char(matlabText));
    s = regexprep(s, '[^a-z0-9]+', '-');
    s = regexprep(s, '^-+|-+$', '');
    if isempty(s)
        s = 'x';
    end
end

function s = chunkLabel(varargin)
%CHUNKLABEL  A unique, valid Quarto/knitr chunk label built from one or
%   more MATLAB text pieces (e.g. a section kind tag, window label,
%   measure type, combo-bin label), each sanitised via labelPiece and
%   joined with hyphens. Uniqueness across the whole document follows
%   from generateQuartoReport's own main loop: each combination of
%   (section kind, window, measure type[, combo label]) is only ever
%   assembled into one chunk.
    pieces = cellfun(@labelPiece, varargin, 'UniformOutput', false);
    s = strjoin(pieces, '-');
end

function text = fillToken(text, token, value)
%FILLTOKEN  Substitute __TOKEN_MD__ (mdLit-escaped) and __TOKEN_R__
%   (rLit-escaped) occurrences of TOKEN with VALUE in TEXT. A no-op for
%   either placeholder VALUE does not contain (empty VALUE is passed
%   through as an empty string on both sides, matching a section that
%   does not use one of the two bin slots, e.g. descriptiveSection's
%   unused BIN2).
    text = strrep(text, ['__' token '_MD__'], mdLit(value));
    text = strrep(text, ['__' token '_R__'], rLit(value));
end

function text = fillCommonTokens(text, windowLabel, measureType, bin1, bin2)
%FILLCOMMONTOKENS  Substitute the tokens every section shares (WINDOW,
%   MEASURETYPE, BIN1, BIN2), each in both its _MD and _R form.
    text = fillToken(text, 'WINDOW', windowLabel);
    text = fillToken(text, 'MEASURETYPE', measureType);
    text = fillToken(text, 'BIN1', bin1);
    text = fillToken(text, 'BIN2', bin2);
end

function text = preambleText(csvFileName, reportTitle, groupColumn, hasGroups)
%PREAMBLETEXT  The YAML header + setup chunk shared by every report kind.
%   REPORTTITLE ("ERP" or "Spectral") names the report in its own title
%   and intro comment. GROUPCOLUMN is the CSV column that plays "window"'s
%   role for this report kind (literally "window" for an ERP export,
%   "frequency_label" for a Spectral one -- see exportMeasurementsCSV.m/
%   exportSpectralCSV.m's own column lists). Every section-builder
%   function below (descriptiveSection, pairedSection, ...) hardcodes
%   `window ==` in its own R filter -- rather than threading GROUPCOLUMN
%   through every one of them, the read chunk here renames GROUPCOLUMN to
%   "window" ONCE, right after read_csv, so the rest of the generated R
%   code (and every section-builder function that emits it) does not need
%   to know or care which report kind it is building for.
%
%   HASGROUPS (see generateQuartoReport's own distinctGroups) does the
%   same thing for the CSV's "group" column: when true, every subject
%   with no group assigned is dropped from `dat` HERE, once, with a
%   printed diagnostic -- so betweenSection/mixedSection can both just
%   assume every remaining row already has a usable group, the same way
%   every section already assumes dataset_type == "subject" was already
%   filtered for it.
    readLines = {'dat <- read_csv(csv_file, show_col_types = FALSE) %>%'};
    if ~strcmp(groupColumn, 'window')
        readLines{end + 1} = sprintf('  rename(window = %s) %%>%%', groupColumn);
    end
    readLines = [readLines, { ...
        '  filter(dataset_type == "subject") %>%' ...
        '  mutate(dataset = factor(dataset), bin = factor(bin))'}];

    lines = [{ ...
        '---' ...
        ['title: "Alakazam ' reportTitle ' Statistical Report"'] ...
        'format:' ...
        '  html:' ...
        '    self-contained: true' ...
        '    toc: true' ...
        '    theme: cosmo' ...
        '    include-in-header:' ...
        '      text: |' ...
        '        <meta name="color-scheme" content="light">' ...
        '        <style>' ...
        '          :root { color-scheme: light !important; }' ...
        '          html, body { background-color: #ffffff !important; }' ...
        '          #TOC, .sidebar, .toc-actions { background-color: #ffffff !important; }' ...
        '        </style>' ...
        'execute:' ...
        '  echo: false' ...
        '  warning: false' ...
        '  message: false' ...
        '---' ...
        '' ...
        '<!--' ...
        ['Alakazam -- statistical report for exported ' reportTitle ' measurements.'] ...
        'Auto-generated, DESIGN-AWARE: unlike a generic report, this one was built' ...
        'specifically for this export''s own bins/windows -- each section below runs' ...
        'the test appropriate to what THAT window/measure actually has (a paired' ...
        't-test for two conditions, a repeated-measures ANOVA for three or more, a' ...
        'one-sample test against zero for a difference/combination bin), rather than' ...
        'one generic loop re-discovering the design at runtime. Edit freely: this is' ...
        'a sensible starting point, not the last word on your design or your prose.' ...
        'Render with: quarto render <this file>.qmd' ...
        '-->' ...
        '' ...
        '```{r}' ...
        '#| label: setup' ...
        '#| include: false' ...
        'pkgs <- c("tidyverse", "rstatix", "ggpubr", "gt")' ...
        'missing <- pkgs[!pkgs %in% rownames(installed.packages())]' ...
        'if (length(missing)) install.packages(missing, repos = "https://cloud.r-project.org")' ...
        'invisible(lapply(pkgs, library, character.only = TRUE))' ...
        '' ...
        'csv_file <- "__CSVFILE_R__"'}, ...
        readLines, ...
        { ...
        '' ...
        'if (n_distinct(dat$dataset) < 2) {' ...
        '  stop("Need at least two subjects (dataset_type == subject) for statistics.")' ...
        '}' ...
        ''}, ...
        groupFilterLines(hasGroups), ...
        { ...
        '' ...
        '# One row per test run below (design/group/p), so the closing section can' ...
        '# report a BH/FDR-adjusted summary ACROSS every group tested, not just' ...
        '# within one group''s own pairwise comparisons.' ...
        'omnibus <- tibble(group = character(), design = character(), test = character(), p = double())' ...
        '' ...
        '# ---- APA-style formatting helpers ----' ...
        '# apa_p/apa_num both drop the leading zero APA convention omits for any' ...
        '# statistic that cannot exceed 1 in magnitude (p, r, eta-squared, ...) --' ...
        '# and, since the regex only matches a value that STARTS with "0.", leave a' ...
        '# statistic that CAN exceed 1 (t, F, M, SD, ...) untouched, so one helper' ...
        '# serves both without the caller having to say which kind of number it is.' ...
        '# Vectorised (ifelse, not if): called on a single test statistic in most' ...
        '# sections, but on a whole column at once (e.g. sig_pw$p.adj, one row per' ...
        '# significant pair) when narrating the ANOVA''s pairwise comparisons -- a' ...
        '# scalar if() on a length > 1 vector is a hard error as of R >= 4.2/4.3.' ...
        'apa_p <- function(p) {' ...
        '  ifelse(is.na(p), "= NA",' ...
        '    ifelse(p < .001, "< .001",' ...
        '      paste("=", sub("^0\\.", ".", sprintf("%.3f", p)))))' ...
        '}' ...
        'apa_num <- function(x, digits = 2) {' ...
        '  ifelse(is.na(x), "NA",' ...
        '    sub("^(-?)0\\.", "\\1.", sprintf(paste0("%.", digits, "f"), x)))' ...
        '}' ...
        '# A three-line APA table (rule above the header, rule below it, rule at the' ...
        '# foot; no vertical rules) via gt, printed with as_raw_html() so it can be' ...
        '# emitted from inside a per-channel for loop in a results:"asis" chunk --' ...
        '# gt''s own auto-print only works for a table that is a chunk''s sole,' ...
        '# top-level, unassigned result, which a table built inside a loop never is.' ...
        '# Numeric columns that happen to be whole numbers everywhere (n, df, ...)' ...
        '# are formatted with 0 decimals, not 3 -- APA never shows a sample size or' ...
        '# degrees of freedom as e.g. "10.000".' ...
        'apa_gt <- function(df, title = NULL) {' ...
        '  is_whole <- function(x) is.numeric(x) && all(x == round(x), na.rm = TRUE)' ...
        '  int_cols <- names(df)[sapply(df, is_whole)]' ...
        '  dec_cols <- setdiff(names(df)[sapply(df, is.numeric)], int_cols)' ...
        '  tbl <- gt(df)' ...
        '  if (!is.null(title)) tbl <- tab_header(tbl, title = title)' ...
        '  if (length(dec_cols) > 0) tbl <- tbl %>% fmt_number(columns = all_of(dec_cols), decimals = 3)' ...
        '  if (length(int_cols) > 0) tbl <- tbl %>% fmt_number(columns = all_of(int_cols), decimals = 0)' ...
        '  tbl %>%' ...
        '    tab_options(' ...
        '      table.border.top.style = "solid", table.border.top.width = px(1.5), table.border.top.color = "black",' ...
        '      table.border.bottom.style = "solid", table.border.bottom.width = px(1.5), table.border.bottom.color = "black",' ...
        '      column_labels.border.bottom.style = "solid", column_labels.border.bottom.width = px(1), column_labels.border.bottom.color = "black",' ...
        '      table_body.hlines.style = "none", table.border.left.style = "none", table.border.right.style = "none",' ...
        '      column_labels.font.weight = "bold", table.font.size = px(13), heading.align = "left"' ...
        '    )' ...
        '}' ...
        '```' ...
        }, ...
        groupsSummaryChunk(hasGroups)];
    text = strrep(strjoin(lines, newline), '__CSVFILE_R__', rLit(csvFileName));
end

function lines = groupFilterLines(hasGroups)
%GROUPFILTERLINES  R lines (still inside the invisible setup chunk) that
%   drop every subject with no group assigned from `dat`, once, when
%   HASGROUPS -- see preambleText's own comment. {} (a no-op splice) when
%   HASGROUPS is false, so a report with no between-subjects grouping
%   generates byte-identical R to before this feature existed.
    if ~hasGroups
        lines = {};
        return;
    end
    lines = { ...
        '' ...
        '# Between-subjects group (see WorkSpace.editGroups): every subject with' ...
        '# no group assigned is unusable for the group-based tests every section' ...
        '# below now runs, so they are set aside here, once, rather than each' ...
        '# section re-deriving the same exclusion from scratch.' ...
        'ungrouped_subjects <- dat %>% filter(is.na(group) | group == "") %>% distinct(dataset) %>% pull(dataset)' ...
        'dat <- dat %>% filter(!is.na(group), group != "") %>% mutate(group = factor(group))' ...
        'if (n_distinct(dat$group) < 2) {' ...
        '  stop("Need at least two groups with a usable subject for between-subjects/mixed statistics.")' ...
        '}'};
end

function chunk = groupsSummaryChunk(hasGroups)
%GROUPSSUMMARYCHUNK  A short, visible chunk (unlike the invisible setup
%   chunk groupFilterLines' own logic lives in) reporting which subjects
%   were excluded for having no group, and the resulting group sizes --
%   printed once, near the top of the report, rather than leaving the
%   reader to infer it from the per-channel counts scattered through every
%   section below. {} (no chunk at all) when HASGROUPS is false.
    if ~hasGroups
        chunk = {};
        return;
    end
    chunk = { ...
        '' ...
        '```{r}' ...
        '#| label: groups-summary' ...
        '#| results: asis' ...
        'if (length(ungrouped_subjects) > 0) {' ...
        '  cat(sprintf("\n\n*Note: %d subject(s) have no group assigned and are excluded from every test below: %s.*\n\n",' ...
        '              length(ungrouped_subjects), paste(ungrouped_subjects, collapse = ", ")))' ...
        '}' ...
        'grp_sizes <- dat %>% distinct(dataset, group) %>% count(group, name = "n_subjects")' ...
        'cat(sprintf("\nBetween-subjects groups: %s.\n\n",' ...
        '            paste(sprintf("%s (*n* = %d)", grp_sizes$group, grp_sizes$n_subjects), collapse = ", ")))' ...
        '```'};
end

function s = blockMatchDiagnosticText()
%BLOCKMATCHDIAGNOSTICTEXT  One line of R, spliced into every section right
%   after its own GRP is built (via the __BLOCKMATCHDIAGNOSTIC__ token),
%   reporting how many of the dataset's total subjects actually matched
%   this block's own window/bin filter, and -- crucially -- what raw bin
%   values actually exist in the data for this window. Discovered the
%   hard way: a report that renders with every per-channel section
%   silently skipped ("fewer than 2 subjects") gives no way to tell WHY
%   without this.
%
%   Separately reports how many of those MATCHED subjects have at least
%   one non-missing (non-NA) value anywhere in the block: matching on
%   window/bin alone (as the count above does) says nothing about whether
%   the VALUE itself is usable -- a subject can match every filter and
%   still contribute only NA rows if the underlying measurement itself
%   failed for them (e.g. SpectralMeasure could not compute this
%   frequency for that subject at all). This is what actually explains a
%   block reporting "N of N matched" while every single per-channel
%   section still says "only 1 of 1" -- filter matching was never the
%   problem, most subjects just have no usable value here.
%
%   Placed before this file's own token substitution loop finishes, so
%   its own __WINDOW_R__ placeholder is filled in by the SAME
%   fillCommonTokens call every other token in the section goes through.
    s = strjoin({ ...
        'cat(sprintf("\n\n*(Matched %d of %d total subject(s) for this block (window: %s), of which %d have at least one non-missing value. Distinct raw bin value(s) seen for this window: %s.)*\n\n",' ...
        '            n_distinct(grp$dataset), n_distinct(dat$dataset), "__WINDOW_R__",' ...
        '            n_distinct(grp$dataset[!is.na(grp$value)]),' ...
        '            paste(unique(dat$bin[dat$window == "__WINDOW_R__"]), collapse = "; ")))'}, newline);
end

