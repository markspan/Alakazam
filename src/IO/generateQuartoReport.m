        '  int_cols <- names(df)[sapply(df, is_whole)]' ...
        '  dec_cols <- setdiff(names(df)[sapply(df, is.numeric)], int_cols)' ...
        '  tbl <- gt(df)' ...
        '  if (!is.null(title)) tbl <- tab_header(tbl, title = title)' ...
        '  if (length(dec_cols) > 0) tbl <- tbl %>% fmt_number(columns = all_of(dec_cols), decimals = 3)' ...
        '  if (length(int_cols) > 0) tbl <- tbl %>% fmt_number(columns = all_of(int_cols), decimals = 0)' ...
        '  tbl %>%' ...
        '    tab_options(' ...
        '      table.border.top.style = "solid", table.border.top.width = px(1.5), table.border.top.color = "black",' ...
        '      table.border.bottom.style = "solid", table.border.bottom.width = px(1.5), table.border.bottom.color = "black",' ...
        '      column_labels.border.bottom.style = "solid", column_labels.border.bottom.width = px(1), column_labels.border.bottom.color = "black",' ...
        '      table_body.hlines.style = "none", table.border.left.style = "none", table.border.right.style = "none",' ...
        '      column_labels.font.weight = "bold", table.font.size = px(13), heading.align = "left"' ...
        '    )' ...
        '}' ...
        '# Classifies a Bayes factor (BF10, alternative over null) by conventional' ...
        '# strength-of-evidence bands (Lee & Wagenmakers, 2013, after Jeffreys, 1961)' ...
        '# and formats it -- used everywhere a Bayesian t-test runs alongside the' ...
        '# frequentist one as a robustness check, the same slot Wilcoxon/Mann-' ...
        '# Whitney/Friedman already occupy: BF10 > 1 favours the alternative' ...
        '# (H1 over H0), < 1 favours the null, so a small BF10 is itself informative' ...
        '# (evidence FOR "no effect", not just "not enough evidence for an effect")' ...
        '# in a way a non-significant p-value alone cannot say.' ...
        'apa_bf <- function(bf) {' ...
        '  if (is.na(bf)) return("NA")' ...
        '  bf10 <- if (bf < 1) 1 / bf else bf' ...
        '  band <- cut(bf10, breaks = c(0, 1, 3, 10, 30, 100, Inf),' ...
        '              labels = c("anecdotal", "anecdotal", "moderate", "strong", "very strong", "extreme"),' ...
        '              right = FALSE, include.lowest = TRUE)' ...
        '  favours <- if (bf >= 1) "H1" else "H0"' ...
        '  sprintf("%s (%s evidence for %s)", apa_num(bf, 2), as.character(band), favours)' ...
        '}' ...
        '# The violin distribution layer every per-channel plot below uses. FILL,' ...
        '# when given, is a literal colour for a single-distribution plot; omitted' ...
        '# (NULL) so the violin instead inherits the plot''s own colour/fill' ...
        '# aesthetic (e.g. aes(colour = group, fill = group)) for a multi-group plot.' ...
        'violin_layers <- function(fill = NULL) {' ...
        '  if (is.null(fill)) {' ...
        '    list(geom_violin(alpha = 0.15, trim = FALSE, linewidth = 0.4))' ...
        '  } else {' ...
        '    list(geom_violin(fill = fill, alpha = 0.15, colour = fill, trim = FALSE, linewidth = 0.4))' ...
        '  }' ...
        '}' ...
        '```' ...
        }, ...
        groupsSummaryChunk(hasGroups)];
    text = strrep(strjoin(lines, newline), '__CSVFILE_R__', rLit(csvFileName));
end

function lines = groupFilterLines(hasGroups)
%GROUPFILTERLINES  R lines (still inside the invisible setup chunk) that
%   drop every subject with no group assigned from `dat`, once, when
%   HASGROUPS -- see preambleText's own comment. {} (a no-op splice) when
%   HASGROUPS is false, so a report with no between-subjects grouping
%   generates byte-identical R to before this feature existed.
    if ~hasGroups
        lines = {};
        return;
    end
    lines = { ...
        '' ...
