        '              n_distinct(d$dataset), length(complete_subjects), n_bins_expected))' ...
        '' ...
        '  m <- tryCatch(lmerTest::lmer(value ~ bin * group + (1 + bin | dataset), data = d,' ...
        '                               control = lme4::lmerControl(optimizer = "bobyqa")), error = function(e) NULL)' ...
        '  used_maximal <- !is.null(m) && !lme4::isSingular(m)' ...
        '  if (is.null(m) || lme4::isSingular(m)) {' ...
        '    m <- tryCatch(lmerTest::lmer(value ~ bin * group + (1 | dataset), data = d,' ...
