        '      table_body.hlines.style = "none", table.border.left.style = "none", table.border.right.style = "none",' ...
        '      column_labels.font.weight = "bold", table.font.size = px(13), heading.align = "left"' ...
        '    )' ...
        '}' ...
        '```' ...
        ''};
end

% ======================================================================= %
%  Intro narrative
% ======================================================================= %
function lines = introLines(summary)
    nSig = sum([summary.clusters.significant]);
    lines = { ...
        '## Cluster Statistics' ...
        '' ...
        sprintf('%s', mdLit(contrastSentence(summary.contrast))) ...
        '' ...
        sprintf(['Tested across %d subject(s), %s permutation(s), %s correction ' ...
            '(cluster-forming *p* < %s, cluster-level %s = %s).'], ...
            summary.nSubjects, permutationLabel(summary.opts.numrandomization), upper(summary.opts.correctm), ...
            numToStr(summary.opts.clusteralpha), alphaLabel(summary.opts.correctm), numToStr(summary.opts.alpha)) ...
        '' ...
        sprintf(['%d cluster(s) were found (positive and negative together); %d were significant ' ...
            'at %s.'], numel(summary.clusters), nSig, alphaClause(summary.opts.alpha)) ...
        '' ...
        ['This is a whole-scalp, whole-epoch test: unlike a pre-chosen channel/window ' ...
         'analysis, it does not assume in advance where or when an effect should appear. ' ...
         'A **cluster** is a contiguous group of (channel, time) points that all crossed the ' ...
         'cluster-forming threshold in the same direction; its own p-value comes from comparing ' ...
         'its summed test statistic against a null distribution built by repeatedly shuffling ' ...
         'condition/group labels and re-running the same clustering procedure -- so it already ' ...
         'accounts for having tested every channel and time point at once, rather than needing a ' ...
         'separate per-comparison correction.'] ...
        ''};
end

function s = contrastSentence(contrast)
    switch contrast.mode
        case 'vsZero'
            s = sprintf('Bin "%s" was tested against zero, within subjects.', contrast.bin);
        case 'paired'
            s = sprintf('Bin "%s" was tested against bin "%s", within subjects (paired).', ...
                contrast.binA, contrast.binB);
        case 'independent'
            s = sprintf('Bin "%s" was tested between two groups (independent samples).', contrast.bin);
    end
end

function s = alphaLabel(correctm)
    if strcmpi(correctm, 'tfce')
        s = '$\\alpha$';
    else
        s = 'cluster $\\alpha$';
    end
end

function s = alphaClause(alpha)
    s = sprintf('*p* < %s', numToStr(alpha));
end

function s = numToStr(x)
    s = regexprep(sprintf('%.4g', x), '^0\.', '.');
end

function s = permutationLabel(numrandomization)
%PERMUTATIONLABEL  NUMRANDOMIZATION for narration -- a plain count, or
%   "all (exhaustive)" when ClusterStats.resolveNumRandomization upgraded
%   it to FieldTrip's own 'all' (an exhaustive 2^N sign-flip enumeration,
%   not a number of randomizations to pass through %d, which would
%   otherwise print each character of "all" as its own code point).
    if ischar(numrandomization) || isstring(numrandomization)
        s = 'all (exhaustive)';
    else
        s = sprintf('%d', numrandomization);
    end
end

% ======================================================================= %
%  Summary table
% ======================================================================= %
function lines = summaryTableLines()
    lines = { ...
        '```{r}' ...
        '#| label: cluster-summary-table' ...
        '#| results: asis' ...
        'summary_tbl <- stat_df %>%' ...
        '  filter(cluster_rank != "NA") %>%' ...
        '  mutate(cluster_rank = as.integer(cluster_rank)) %>%' ...
        '  group_by(cluster_rank, sign) %>%' ...
        '  summarise(' ...
        '    p = first(cluster_p), significant = first(significant),' ...
        '    channels = n_distinct(channel), time_from_ms = min(time_ms), time_to_ms = max(time_ms),' ...
        '    .groups = "drop"' ...
        '  ) %>%' ...
        '  arrange(p)' ...
        'if (nrow(summary_tbl) > 0) {' ...
        '  cat(as_raw_html(apa_gt(summary_tbl, "Clusters Found")))' ...
        '} else {' ...
        '  cat("\n\nNo clusters were found at all (not even a non-significant one) -- every point fell ' ...
             'below the cluster-forming threshold.\n\n")' ...
        '}' ...
        '```' ...
        ''};
end

