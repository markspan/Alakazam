% ======================================================================= %
%  Per-cluster detail (strongest few, already p-sorted -- see this file's
%  own header on why not every spurious tiny cluster gets a full section)
% ======================================================================= %
function lines = clusterDetailLines(summary)
    lines = {'## Where and When: the Strongest Clusters' ''};
    nShow = min(5, numel(summary.clusters));
    if nShow == 0
        lines = [lines, {'No clusters to show.' ''}];
        return;
    end
    for r = 1:nShow
        c = summary.clusters(r);
        lines = [lines, oneClusterLines(r, c)]; %#ok<AGROW>
    end
end

function lines = oneClusterLines(rank, c)
    sigWord = 'not significant';
    if c.significant
        sigWord = 'significant';
    end
    chLit = rLit(strjoin(c.channels, ', '));
    lines = { ...
        sprintf('### Cluster %d (%s, %s)', rank, c.sign, sigWord) ...
        '' ...
        sprintf(['A %s cluster spanning %s, %.0f to %.0f ms (*p* %s, %d point(s)).'], ...
            c.sign, mdLit(strjoin(c.channels, ', ')), c.timeRangeMs(1), c.timeRangeMs(2), ...
            pStr(c.pValue), c.nPoints) ...
        '' ...
        '::: {layout-ncol=2}' ...
        '' ...
        sprintf('```{r}') ...
        sprintf('#| label: topo-%d', rank) ...
        sprintf('#| fig-width: 4') ...
        sprintf('#| fig-height: 4') ...
        sprintf('t_lo <- %g; t_hi <- %g', c.timeRangeMs(1), c.timeRangeMs(2)) ...
        sprintf('pts <- stat_df %%>%% filter(time_ms >= t_lo, time_ms <= t_hi) %%>%%') ...
        sprintf('  group_by(channel, x, y) %%>%% summarise(statistic = mean(statistic), .groups = "drop")') ...
        sprintf('in_cluster <- stat_df %%>%% filter(channel %%in%% c(%s), time_ms >= t_lo, time_ms <= t_hi) %%>%%', ...
            strjoin(cellfun(@(ch) ['"' rLit(ch) '"'], c.channels, 'UniformOutput', false), ', ')) ...
        sprintf('  distinct(channel)') ...
        sprintf('tp <- ggplot() +') ...
        sprintf('  geom_path(data = outline_df, aes(x = x, y = y, group = outline_id), colour = "grey60") +') ...
        sprintf('  geom_point(data = pts, aes(x = x, y = y, colour = statistic), size = 5) +') ...
        sprintf(['  geom_point(data = pts %%>%% filter(channel %%in%% in_cluster$channel), ' ...
            'aes(x = x, y = y), shape = 1, size = 7, colour = "black", stroke = 1) +']) ...
        sprintf(['  geom_text(data = pts, aes(x = x, y = y, label = channel), ' ...
            'size = 2.2, vjust = -1.1, colour = "grey20") +']) ...
        sprintf('  scale_colour_gradient2(low = "#c0392b", mid = "white", high = "#2980b9", midpoint = 0) +') ...
        sprintf('  coord_fixed() + theme_void() + labs(title = "Where (mean over cluster window)")') ...
        sprintf('print(tp)') ...
        '```' ...
        '' ...
        sprintf('```{r}') ...
        sprintf('#| label: timecourse-%d', rank) ...
        sprintf('#| fig-width: 5') ...
        sprintf('#| fig-height: 4') ...
        sprintf('wf <- waveform_df %%>%% filter(channel %%in%% c(%s))', ...
            strjoin(cellfun(@(ch) ['"' rLit(ch) '"'], c.channels, 'UniformOutput', false), ', ')) ...
        sprintf('tc <- ggplot(wf, aes(x = time_ms, y = value, colour = condition, fill = condition)) +') ...
        sprintf('  annotate("rect", xmin = t_lo, xmax = t_hi, ymin = -Inf, ymax = Inf, alpha = 0.12, fill = "grey40") +') ...
        sprintf('  stat_summary(fun = mean, geom = "line", linewidth = 0.8) +') ...
        sprintf('  stat_summary(fun.data = mean_se, geom = "ribbon", alpha = 0.15, colour = NA) +') ...
        sprintf('  geom_hline(yintercept = 0, linetype = "dashed", colour = "grey60") +') ...
        sprintf('  labs(x = "Time (ms)", y = "Amplitude", title = "When (shaded = cluster window)") +') ...
        sprintf('  theme_minimal(base_size = 11)') ...
        sprintf('print(tc)') ...
        '```' ...
        '' ...
        ':::' ...
        ''};
end

function s = pStr(p)
    if p < .001
        s = '< .001';
    else
        s = ['= ' regexprep(sprintf('%.3f', p), '^0\.', '.')];
    end
end

% ======================================================================= %
%  String-escaping helpers (see generateQuartoReport.m's own copies of
%  these -- duplicated rather than shared, both local-only there too)
% ======================================================================= %
function s = rLit(matlabText)
    s = strrep(char(matlabText), '\', '\\');
    s = strrep(s, '"', '\"');
end

function s = mdLit(matlabText)
    s = char(matlabText);
    special = {'\', '*', '_', '#', '[', ']', '`', '<', '>'};
    for i = 1:numel(special)
        s = strrep(s, special{i}, ['\' special{i}]);
    end
end
