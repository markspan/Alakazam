        '          #TOC, .sidebar, .toc-actions { background-color: #ffffff !important; }' ...
        '        </style>' ...
        'execute:' ...
        '  echo: false' ...
        '  warning: false' ...
        '  message: false' ...
        '---' ...
        '' ...
        '<!--' ...
        'Alakazam -- cluster-based permutation statistics report (Maris &' ...
        'Oostenveld, 2007), via FieldTrip''s ft_timelockstatistics. Unlike the' ...
        'ERP/Spectral Measure reports, the test itself already ran in MATLAB (see' ...
        'ClusterStats.m); this report narrates and plots that precomputed result,' ...
        'it does not run any statistics of its own. Edit freely: this is a' ...
        'sensible starting point, not the last word on your own plots or prose.' ...
        'Render with: quarto render <this file>.qmd' ...
        '-->' ...
        '' ...
        '```{r}' ...
        '#| label: setup' ...
