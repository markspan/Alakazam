% ======================================================================= %
%  Per-channel noise
% ======================================================================= %
function lines = channelNoiseLines()
    lines = { ...
        '## Noise by Channel' ...
        '' ...
        ['Which electrodes, on which subjects. A whole row standing out is a noisy recording; a ' ...
         'single bright cell is one bad electrode on one subject, which is the case interpolation ' ...
         'is actually for.'] ...
        '' ...
        ['Colour is noise **among the samples that survived**, so the worst channels are the ones ' ...
         'colour cannot show: a channel rejected in every trial has nothing left to take a median ' ...
         'of and would otherwise sit here as an unremarkable grey cell, and an interpolated one ' ...
         'shows the noise of its neighbours rather than its own. Both are marked instead of left ' ...
         'to the colour scale.'] ...
        '' ...
        '```{r}' ...
        '#| label: channel-noise-map' ...
        '#| fig-height: 7' ...
        '# Weighted by n_trials rather than a plain mean over bins: bins routinely differ in' ...
        '# trial count, and an unweighted mean would let a 12-trial bin count as heavily as a' ...
        '# 200-trial one when deciding whether a channel is mostly gone.' ...
        'chan <- qual %>%' ...
        '  group_by(dataset, channel) %>%' ...
        '  summarise(baseline_sd_uv = median(baseline_sd_uv, na.rm = TRUE),' ...
        '            pct_flagged = weighted.mean(pct_flagged, n_trials, na.rm = TRUE),' ...
        '            pct_interpolated = weighted.mean(pct_interpolated, n_trials, na.rm = TRUE),' ...
        '            .groups = "drop")' ...
        'if (all(is.na(chan$baseline_sd_uv)) && all(chan$pct_flagged == 0, na.rm = TRUE)) {' ...
        '  cat("\n\nNo per-channel noise estimates are available.\n\n")' ...
        '} else {' ...
        '  gone <- chan %>% filter(!is.na(pct_flagged), pct_flagged > 20)' ...
        '  interp <- chan %>% filter(!is.na(pct_interpolated), pct_interpolated > 20)' ...
        '  cp <- ggplot(chan, aes(x = channel, y = dataset)) +' ...
        '    geom_tile(aes(fill = baseline_sd_uv)) +' ...
        '    scale_fill_viridis_c(option = "magma", direction = -1, name = "SD (uV)", na.value = "grey90") +' ...
        '    geom_point(data = gone, shape = 4, size = 1.3, stroke = 0.6, colour = "white") +' ...
        '    geom_point(data = interp, shape = 1, size = 1.6, stroke = 0.6, colour = "black") +' ...
        '    labs(x = NULL, y = NULL,' ...
        '         subtitle = paste("x  flagged in >20% of trials (grey = nothing left to measure)",' ...
        '                          "o  interpolated in >20% of trials", sep = "    ")) +' ...
        '    theme_minimal(base_size = 9) +' ...
        '    theme(axis.text.x = element_text(angle = 90, vjust = 0.5, hjust = 1, size = 6),' ...
        '          plot.subtitle = element_text(size = 7, colour = "grey30"))' ...
        '  print(cp)' ...
        '}' ...
        '```' ...
        ''};
end

