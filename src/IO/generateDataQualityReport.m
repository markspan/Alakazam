function qmdText = generateDataQualityReport(entries, summaryCsvName, trialCsvName, smeCsvName)
%GENERATEDATAQUALITYREPORT  A Quarto (.qmd) report on per-subject ERP data
%   quality: rendering it (self-contained HTML) produces a per-subject
%   overview table, the condition-wise rejection figure that is the whole
%   point of the exercise, per-trial noise distributions, a subject x
%   channel noise map, and a short "worth a look" list naming the subjects
%   and channels that stand out.
%
%   Adapted from the data-quality assessment section of Mathot &
%   Vilotijevic (2023), "Methods in cognitive pupillometry: Design,
%   preprocessing, and statistical analysis" (Behav Res Methods 55,
%   3055-3077) -- see dataQualityMetrics.m's own header for the
%   pupillometry-to-ERP mapping each metric comes from, and for the two
%   places the translation deliberately departs from the original.
%
%   Like generateClusterStatsReport.m (and unlike generateQuartoReport.m,
%   whose R code runs the actual statistical tests), every number here was
%   already computed in MATLAB by dataQualityMetrics; this report's own R
%   code narrates, tabulates and plots a precomputed result. The one
%   exception is the omnibus test for whether rejection rate differs
%   BETWEEN bins, which is a genuine inferential question about the export
%   as a whole rather than about any one subject, so it belongs with the
%   other cross-subject statistics in R.
%
%   ENTRIES is the same struct array exportDataQualityCSVs was handed (only
%   its length and grouping are used here, to decide which sections can
%   run at all); SUMMARYCSVNAME/TRIALCSVNAME are bare filenames, resolved
%   relative to the .qmd's own folder.
%
%   Requires the R packages tidyverse and gt (auto-installed by the
%   report's own setup chunk on first render, same as the other two report
%   generators) plus a working Quarto installation.
%
%   See also DATAQUALITYMETRICS, EXPORTDATAQUALITYCSVS,
%   ALAKAZAM.ONEXPORTDATAQUALITY.
    if isempty(entries)
        throw(MException('Alakazam:generateDataQualityReport', ...
            ['I''m afraid a data-quality report needs at least one Averaged dataset ' ...
             'with segmented data behind it.']));
    end
    hasGroups = numel(distinctGroups(entries)) >= 2;
    if nargin < 4 || isempty(smeCsvName)
        smeCsvName = '';
    end

    lines = [ ...
        preambleLines(summaryCsvName, trialCsvName, smeCsvName), ...
        introLines(numel(entries)), ...
        overviewLines(), ...
        rejectionByBinLines(), ...
        baselineNoiseLines(), ...
        noiseOverSessionLines(), ...
        channelNoiseLines(), ...
        smeLines(smeCsvName), ...
        groupComparisonLines(hasGroups), ...
        attentionLines()];
    qmdText = strjoin(lines, newline);
end

% ======================================================================= %
function labels = distinctGroups(entries)
    groups = {entries.group};
    labels = unique(groups(~cellfun(@isempty, groups)));
end

% ======================================================================= %
%  Preamble
% ======================================================================= %
function lines = preambleLines(summaryCsvName, trialCsvName, smeCsvName)
    lines = [ReportDoc.yamlHeader('Alakazam Data Quality Report'), { ...
        '' ...
        '<!--' ...
        'Alakazam -- per-subject ERP data-quality report. Every per-subject number was' ...
        'computed in MATLAB (see dataQualityMetrics.m, whose own header records where' ...
        'the metric set was adapted from); this report narrates and plots them. It' ...
        'excludes nothing on your behalf -- see the closing section. Edit freely.' ...
        'Render with: quarto render <this file>.qmd' ...
        '-->' ...
        '' ...
        '```{r}' ...
        '#| label: setup' ...
        '#| include: false' ...
        }, ReportDoc.packageBootstrap({'tidyverse', 'gt'}), { ...
        '' ...
        sprintf('qual <- read_csv("%s", show_col_types = FALSE)', rLit(summaryCsvName)) ...
        sprintf('trl  <- read_csv("%s", show_col_types = FALSE)', rLit(trialCsvName)) ...
        smeReadLine(smeCsvName) ...
        '' ...
        '# One row per subject: every subject_* column is constant within a dataset' ...
        '# (dataQualityMetrics computes them once per subject and exportDataQualityCSVs' ...
        '# repeats them onto every bin x channel row), so first() is exact here, not an' ...
        '# arbitrary pick among differing values.' ...
        'subj <- qual %>%' ...
        '  group_by(dataset, group, session) %>%' ...
        '  summarise(' ...
        '    n_trials = first(subject_n_trials),' ...
        '    n_channels = first(subject_n_channels),' ...
        '    pct_rejected = first(subject_pct_trials_rejected),' ...
        '    pct_flagged = first(subject_pct_channel_epochs_flagged),' ...
        '    pct_interpolated = first(subject_pct_channel_epochs_interpolated),' ...
        '    pct_outlier = first(subject_pct_baseline_outlier_trials),' ...
        '    pct_truncated = first(subject_pct_trials_truncated),' ...
        '    max_truncated_pct = first(subject_max_truncated_pct),' ...
        '    rejection_ran = first(subject_rejection_ran),' ...
        '    n_discarded = first(subject_n_trials_rejected),' ...
        '    n_kept = first(subject_n_trials_kept),' ...
        '    n_truncated = first(subject_n_trials_truncated),' ...
        '    median_baseline_sd = median(baseline_sd_uv, na.rm = TRUE),' ...
        '    median_sme = median(sme_uv, na.rm = TRUE),' ...
        '    .groups = "drop"' ...
        '  ) %>%' ...
        '  arrange(desc(pct_rejected))' ...
        '' ...
        'alz_blue <- "#4a7fc9"' ...
        'alz_red  <- "#d0454a"' ...
        '' ...
        }, ReportDoc.apaHelpers(), { ...
        '```' ...
        ''}];
end

function line = smeReadLine(smeCsvName)
%SMEREADLINE  Read the per-window SME table, or stand in an empty one of
%   the same shape when this export had no Measure results to score. The
%   section below then needs only ONE emptiness check (nrow == 0), rather
%   than separate "file absent" and "file empty" branches that would both
%   have to be kept in step with it.
    if isempty(smeCsvName)
        line = ['wsme <- tibble(dataset = character(), group = character(), window = character(), ' ...
            'bin = character(), channel = character(), measure = character(), method = character(), ' ...
            'sme_uv = double(), score = double())'];
    else
        line = sprintf('wsme <- read_csv("%s", show_col_types = FALSE)', rLit(smeCsvName));
    end
end

% ======================================================================= %
%  Intro
% ======================================================================= %
function lines = introLines(nEntries)
    lines = { ...
        '## What This Report Is' ...
        '' ...
        sprintf(['Data quality for each of the %d subject(s) whose Average currently sits in this ' ...
            'workspace, computed from the segmented data each average was actually built from.'], nEntries) ...
        '' ...
        ['The number that matters here is not how much data you lost, but **whether you lost it ' ...
         'evenly across conditions**. A high but even rejection rate costs statistical power; an ' ...
         'uneven one biases the contrast itself, because the surviving trials in one condition are ' ...
         'no longer a fair sample of that condition.'] ...
        '' ...
        'What each metric is:' ...
        '' ...
        '| Metric | What it tells you |' ...
        '|---|---|' ...
        ['| % trials rejected | How much of the recording survived artefact rejection. See the note ' ...
         'directly below: with no artefact step in the chain, an empty trial means an epoch that ' ...
         'could not be cut, not one anything rejected |'] ...
        ['| % trials truncated | Trials whose epoch ran off the start or end of the recording. They ' ...
         'still enter the average, with less data at the ends than their neighbours |'] ...
        ['| % trials rejected **per bin** | Whether that loss is even across conditions. This is ' ...
         'the one that can invalidate a result rather than just weaken it |'] ...
        ['| % channel-epochs flagged | Loss confined to single channels rather than whole trials, ' ...
         'usually one bad electrode. Note this is a share of *all* channel-epochs: one electrode ' ...
         'dead in every trial of a 64-channel montage is only 1.6% here, so read it with the ' ...
         'per-channel map below rather than on its own |'] ...
        ['| % channel-epochs interpolated | Channel-epochs that were *reconstructed* from ' ...
         'neighbouring electrodes rather than discarded. Not loss, but not measurement either: ' ...
         'these samples are an estimate, and a spatially widespread artefact (a blink spans the ' ...
         'frontal electrodes at once) can be reproduced rather than removed by the reconstruction |'] ...
        ['| Pre-stimulus SD (uV) | Per-trial noise. Measured as *variability* over the pre-stimulus ' ...
         'window, not its mean, which baseline correction sets to zero by construction |'] ...
        ['| % baseline outlier trials | Trials whose pre-stimulus noise is extreme *for that ' ...
         'subject*, at \|z\| > 2 against their own distribution |'] ...
        ['| SME (uV) | Standardized measurement error (Luck et al., 2021), the ERP field''s own ' ...
         'single-subject quality statistic |'] ...
        '' ...
        ['Nothing below has been excluded from your data. Exclusion criteria are best set in advance ' ...
         'and reported openly, so this report tells you what is there and leaves the decision with ' ...
         'you.'] ...
        '' ...
        '```{r}' ...
        '#| label: empty-trial-provenance' ...
        '#| results: asis' ...
        '# A trial counts as "rejected" when every channel of it is NaN, and there are' ...
        '# TWO ways to get that: an artefact step removed it, or DefineBins could not' ...
        '# cut the epoch at all (an anchor event past the end of the recording). The' ...
        '# two are identical in the data, so rather than assert a cause, this says' ...
        '# which one applies from whether any artefact step is actually in the chain.' ...
        'any_lost <- any(subj$pct_rejected > 0, na.rm = TRUE)' ...
        'ran <- subj$rejection_ran' ...
        'if (any_lost && all(ran == 0, na.rm = TRUE) && !all(is.na(ran))) {' ...
        '  cat(paste0("\n::: {.callout-important}\n## These trials were not rejected by anything\n\n",' ...
        '             "No ArtefactDetect or ManualReject step appears in these datasets, so nothing ",' ...
        '             "removed the empty trials counted below. They are epochs **DefineBins could not ",' ...
        '             "cut**: the anchor event sat past the end of the recording, or had no usable ",' ...
        '             "latency, so the epoch was never filled with data. Check the event codes near ",' ...
        '             "the end of your recordings, and the epoch window against how long they run ",' ...
        '             "on for after the last event.\n:::\n\n"))' ...
        '} else if (any_lost && any(ran == 0, na.rm = TRUE)) {' ...
        '  mixed <- subj$dataset[!is.na(ran) & ran == 0]' ...
        '  cat(sprintf(paste0("\n*No artefact-rejection step is present for %s, so any empty trials ",' ...
        '                     "there are epochs DefineBins could not cut rather than rejections.*\n\n"),' ...
        '              paste(mixed, collapse = ", ")))' ...
        '}' ...
        '```' ...
        ''};
end

