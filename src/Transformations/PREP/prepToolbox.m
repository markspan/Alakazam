function spec = prepToolbox()
%PREPTOOLBOX  The PREP pipeline, described for TransTools.EnsureToolbox.
%
%   PINNED TO TAG v0.57.0 (March 2025), the current release, whose
%   prepPipeline.m is identical to the repository's master branch. It
%   replaced v0.56.0 on 10 October 2026; between the two only PREP's EEGLAB
%   dialog (pop_prepPipeline), its own report and its version number
%   changed, none of which this calls, so results are the same.
%
%   KEPT AS IT IS: the v0.57.0 tag's getPrepVersion still says
%   'PrepPipeline0.56.0', as the number was raised one commit after the
%   tag. PREP's report of its version is recorded as PREP gives it
%   (EEG.etc.alz.prep.version, from prepVersion in PREP.m), so a result
%   made with this pin names 0.56.0; the install folder
%   (EEG-Clean-Tools-0.57.0) says which it was.
%
%   The archive is EEG-Clean-Tools, which holds PREP in its PrepPipeline folder;
%   PREP's own EEGLAB plugin puts that folder and all its subfolders on the
%   path, so this does the same (Subfolders).
%
%   The probe is getPrepDefaults, not prepPipeline: it lives in a subfolder,
%   so finding it means the helpers PREP calls are on the path too, not
%   just its entry point.
%
%   See also PREP, TRANSTOOLS.ENSURETOOLBOX.
    spec = struct( ...
        'Name',       'the PREP pipeline', ...
        'Feature',    'PREP', ...
        'Probe',      'getPrepDefaults', ...
        'ProbeFile',  'prepPipeline.m', ...
        'Folder',     'PrepPipeline', ...
        'Url',        'https://github.com/VisLab/EEG-Clean-Tools/archive/refs/tags/v0.57.0.zip', ...
        'Version',    '0.57.0', ...
        'Release',    'EEG-Clean-Tools-0.57.0', ...
        'About',      ['PREP is free, open-source (GPL) software by Bigdely-Shamlo, Mullen, ' ...
                       'Kothe, Su and Robbins (2015) for the standardised early stages of EEG ' ...
                       'preprocessing: line noise, bad channels and a robust average reference.'], ...
        'Subfolders', true);
end
