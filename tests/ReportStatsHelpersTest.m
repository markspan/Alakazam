classdef ReportStatsHelpersTest < matlab.unittest.TestCase
%REPORTSTATSHELPERSTEST  The R helpers the statistics report rests on, run in R.
%
%   Each case prints what it found and the MATLAB side reads it back. The cases
%   skip where Rscript or a package is absent. These are the functions behind
%   four corrections: the signed rank-biserial, the seeded BCa interval, one
%   value per person, and the Huynh-Feldt p beside a model that assumes sphericity.
%
%   See also REPORTFIXTURES, QUARTOREPORTRENDERTEST.
    methods (TestClassSetup)
        function needR(testCase)
            root = fileparts(fileparts(mfilename('fullpath')));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture(fullfile(root, 'tests')));
            testCase.assumeNotEmpty(ReportFixtures.rscriptExe(), 'Rscript was not found.');
        end
    end

    methods (Test)
        function theRankBiserialIsSignedAndIsTheRealOne(testCase)
            v = testCase.values([ ...
                'x <- c(-1.2, -0.8, -1.5, -0.4, -2.1, -0.9, -1.1, 0.2, -0.7, -1.6)' newline ...
                'r <- rank(abs(x)); truth <- (sum(r[x > 0]) - sum(r[x < 0])) / sum(r)' newline ...
                'one <- rank_biserial_ci(x, mu = 0)' newline ...
                'pair <- rank_biserial_ci(x, rep(0, 10), paired = TRUE)' newline ...
                'emit(truth, one$effsize, pair$effsize)']);
            testCase.verifyLessThan(v(1), 0);
            testCase.verifyEqual(v(2), v(1), 'AbsTol', 1e-9);
            testCase.verifyEqual(v(3), v(1), 'AbsTol', 1e-9);
        end

        function aTwoGroupRankBiserialRunsWithTheTest(testCase)
            v = testCase.values([ ...
                'g <- tibble(value = c(1:10, 6:15), group = factor(rep(c("a", "b"), each = 10)))' newline ...
                'emit(rank_biserial_ci(value ~ group, data = g)$effsize, unname(t.test(value ~ group, data = g)$statistic))']);
            testCase.verifyEqual(sign(v(1)), sign(v(2)));
        end

        function cohensDIsRstatixsPointEstimate(testCase)
            v = testCase.values([ ...
                'set.seed(1); x <- rnorm(20, 0.5); y <- rnorm(25)' newline ...
                'a <- cohens_d_ci(x)' newline ...
                'd <- tibble(value = c(x, y), group = factor(rep(c("a", "b"), c(20, 25))))' newline ...
                'b <- cohens_d_ci(x, y)' newline ...
                'emit(a$effsize, rstatix::cohens_d(tibble(value = x), value ~ 1, mu = 0)$effsize, ' ...
                'b$effsize, rstatix::cohens_d(d, value ~ group)$effsize, a$conf.low, a$conf.high, b$conf.low, b$conf.high)']);
            testCase.verifyEqual(v(1), v(2), 'AbsTol', 1e-9);
            testCase.verifyEqual(v(3), v(4), 'AbsTol', 1e-9);
            testCase.verifyLessThan(v(5), v(1));
            testCase.verifyGreaterThan(v(6), v(1));
            testCase.verifyLessThan(v(7), v(3));
            testCase.verifyGreaterThan(v(8), v(3));
        end

        function theIntervalIsTheSameEveryRender(testCase)
            v = testCase.values([ ...
                'set.seed(2); x <- rnorm(20, 0.5)' newline ...
                'a <- cohens_d_ci(x); set.seed(3); runif(5); b <- cohens_d_ci(x)' newline ...
                'emit(a$conf.low, b$conf.low, a$conf.high, b$conf.high, alz_boot_draws)']);
            testCase.verifyEqual(v(1), v(2));
            testCase.verifyEqual(v(3), v(4));
            testCase.verifyGreaterThanOrEqual(v(5), 2000);
        end

        function aConstantDifferenceGivesNoIntervalAndNoError(testCase)
            v = testCase.values('a <- cohens_d_ci(rep(1, 10)); emit(is.na(a$conf.low))');
            testCase.verifyEqual(v, 1);
        end

        function eachPersonCountsOnce(testCase)
            v = testCase.values([ ...
                'd <- tibble(dataset = c("r1", "r2", "r3"), person_id = factor(c("p", "p", "q")), group = "g",' newline ...
                '  bin = "A", channel = "Cz", window = "w", measure_type = "mean_amplitude", value = c(1, 3, 10))' newline ...
                'o <- per_person(d) %>% arrange(person_id)' newline ...
                'emit(nrow(o), o$value[1], o$value[2], o$dataset[1] == "p")']);
            testCase.verifyEqual(v, [2 2 10 1]);
        end

        function oneRecordingPerPersonIsLeftAlone(testCase)
            v = testCase.values([ ...
                'd <- tibble(dataset = c("r1", "r2"), person_id = factor(c("p", "q")), bin = "A",' newline ...
                '  channel = "Cz", window = "w", measure_type = "mean_amplitude", value = c(1, 3))' newline ...
                'emit(identical(per_person(d), d))']);
            testCase.verifyEqual(v, 1);
        end

        function anglesAreAveragedOnTheCircle(testCase)
            v = testCase.values([ ...
                'd <- tibble(dataset = c("r1", "r2"), person_id = factor(c("p", "p")), bin = "A",' newline ...
                '  channel = "Cz", window = "w", measure_type = "phase", value = c(3.1, -3.1))' newline ...
                'emit(abs(per_person(d)$value))']);
            testCase.verifyGreaterThan(v, 3, 'The mean of 3.1 and -3.1 on the circle is pi, not 0.');
        end

        function aPersonsTwoConditionsStayApart(testCase)
            v = testCase.values([ ...
                'd <- tibble(dataset = c("r1", "r2", "r1", "r2"), person_id = factor("p"), bin = c("A", "A", "B", "B"),' newline ...
                '  channel = "Cz", window = "w", measure_type = "mean_amplitude", value = c(1, 3, 5, 7))' newline ...
                'o <- per_person(d) %>% arrange(bin); emit(nrow(o), o$value)']);
            testCase.verifyEqual(v, [2 2 6]);
        end

        function theHuynhFeldtPIsTheCorrectedOne(testCase)
            v = testCase.values([ ...
                'set.seed(4); N <- 16; k <- 4; S <- 0.85 ^ abs(outer(1:k, 1:k, "-"))' newline ...
                'Y <- matrix(rnorm(N * k), N, k) %*% chol(S) + rep(c(0, 0, 1, 1), each = N)' newline ...
                'd <- tibble(person_id = factor(rep(1:N, k)), bin = factor(rep(1:k, each = N)), value = as.vector(Y))' newline ...
                'h <- huynh_feldt(d, "bin")' newline ...
                'm <- suppressMessages(lmerTest::lmer(value ~ bin + (1 | person_id), data = d))' newline ...
                'a <- as.data.frame(anova(m)); fit <- rstatix::anova_test(data = as.data.frame(d), formula = value ~ bin + Error(person_id / bin))' newline ...
                'e <- as.data.frame(fit[["Sphericity Corrections"]])' newline ...
                'emit(nrow(h), h$epsilon, h$p, a[["Pr(>F)"]][1], h$n_complete, a[["F value"]], as.data.frame(fit[["ANOVA"]])$F, min(as.numeric(e$HFe), 1))']);
            testCase.verifyEqual(v(1), 1);
            testCase.verifyLessThan(v(2), 1);
            testCase.verifyGreaterThan(v(3), v(4), 'The correction makes the test more conservative.');
            testCase.verifyEqual(v(5), 16);
            testCase.verifyEqual(v(6), v(7), 'AbsTol', 1e-2, 'The model with no slopes is that ANOVA.');
            testCase.verifyEqual(v(2), v(8), 'AbsTol', 1e-3);
        end

        function aPersonMissingACellIsLeftOutOfTheCorrection(testCase)
            v = testCase.values([ ...
                'set.seed(5); N <- 10; k <- 3' newline ...
                'd <- tibble(person_id = factor(rep(1:N, k)), bin = factor(rep(1:k, each = N)), value = rnorm(N * k))' newline ...
                'd <- d[-1, ]; emit(huynh_feldt(d, "bin")$n_complete)']);
            testCase.verifyEqual(v, 9);
        end

        function twoLevelsHaveNothingToCorrect(testCase)
            v = testCase.values([ ...
                'set.seed(6); N <- 10' newline ...
                'd <- tibble(person_id = factor(rep(1:N, 2)), bin = factor(rep(1:2, each = N)), value = rnorm(N * 2))' newline ...
                'emit(nrow(huynh_feldt(d, "bin")))']);
            testCase.verifyEqual(v, 0);
        end

        function aMixedDesignFindsItsInteraction(testCase)
            v = testCase.values([ ...
                'set.seed(7); N <- 12; k <- 3' newline ...
                'd <- tibble(person_id = factor(rep(1:N, k)), bin = factor(rep(1:k, each = N)), value = rnorm(N * k),' newline ...
                '  group = factor(rep(rep(c("a", "b"), each = N / 2), k)))' newline ...
                'h <- huynh_feldt(d, "bin", "group"); emit(nrow(h), "bin:group" %in% h$key, term_key("group:bin") == "bin:group")']);
            testCase.verifyEqual(v, [2 1 1]);
        end

        function friedmanUsesThePeopleWithEveryCondition(testCase)
            v = testCase.values([ ...
                'set.seed(8); N <- 10; k <- 3' newline ...
                'd <- tibble(person_id = factor(rep(1:N, k)), bin = factor(rep(1:k, each = N)), value = rnorm(N * k))' newline ...
                'keep <- d[-1, ]; w <- keep %>% pivot_wider(names_from = bin, values_from = value) %>% drop_na()' newline ...
                'p <- friedman.test(as.matrix(select(w, -person_id)))$p.value' newline ...
                'emit(friedman_note(keep) == apa_p(p))']);
            testCase.verifyEqual(v, 1);
        end

        function theSlopelessModelIsWhatLme4Leaves(testCase)
        %   The premise of the section: with one value per person per bin lme4
        %   refuses the slopes, whichever way the data are incomplete.
            v = testCase.values([ ...
                'set.seed(9); N <- 12' newline ...
                'd <- tibble(person_id = factor(rep(1:N, 3)), bin = factor(rep(1:3, each = N)), value = rnorm(N * 3))' newline ...
                'try1 <- function(x) is.null(tryCatch(lme4::lmer(value ~ bin + (1 + bin | person_id), data = x), error = function(e) NULL))' newline ...
                'emit(try1(d), try1(d[-c(3, 17), ]), anyDuplicated(d[c("person_id", "bin")]) > 0)']);
            testCase.verifyEqual(v, [1 1 0]);
        end
    end

    methods
        function v = values(testCase, code)
            root = fileparts(fileparts(mfilename('fullpath')));
            rscripts = strrep(fullfile(root, 'src', 'Reports', 'rscripts'), '\', '/');
            setup = [ ...
                'suppressPackageStartupMessages({library(dplyr); library(tidyr); library(tibble)})' newline ...
                'for (f in c("apa-helpers.R", "violin-layers.R")) {' newline ...
                '  lines <- readLines(file.path("' rscripts '", f))' newline ...
                '  eval(parse(text = lines))' newline ...
                '}' newline ...
                'emit <- function(...) cat("VALUES", as.numeric(c(...)), "\n")' newline];
            [status, output] = ReportFixtures.runRscript([setup code]);
            testCase.assumeFalse(contains(output, 'there is no package called'), output);
            testCase.assertEqual(status, 0, output);
            tokens = regexp(output, 'VALUES ([^\r\n]*)', 'tokens', 'once');
            testCase.assertNotEmpty(tokens, output);
            v = str2double(strsplit(strtrim(tokens{1})));
        end
    end
end
